export async function POST(req: NextRequest) {
  // SYNC_SECRET認証（手動実行用・一回限り）
  const syncSecret = process.env.SYNC_SECRET;
  const authHeader = req.headers.get("Authorization");
  if (!syncSecret || authHeader !== `Bearer ${syncSecret}`) {
    return NextResponse.json({ ok: false, error: "Unauthorized" }, { status: 401 });
  }

  try {
    // ① station_map データ生成（STATION_WARD_MAP ∪ STATION_LINE_MAP）
    const stationTokens = new Set<string>([
      ...Object.keys(STATION_WARD_MAP),
      ...Object.keys(STATION_LINE_MAP),
    ]);

    const stationRows = Array.from(stationTokens).map((token) => {
      const realproLines = STATION_LINE_MAP[token] ?? [];
      const itandiLines = realproLines.flatMap((line) => {
        const v = ITANDI_LINE_MAP_FILL[line];
        if (!v) return [];
        return Array.isArray(v) ? v : [v];
      });
      const reinsLine =
        realproLines.length > 0
          ? (REINS_LINE_MAP[realproLines[0]] ?? null)
          : null;
      return {
        token,
        ward: STATION_WARD_MAP[token] ?? null,
        realpro_lines: realproLines,
        itandi_lines: itandiLines,
        reins_line: reinsLine,
        confidence: 100,
        source: "hardcoded",
      };
    });

    // ② region_map データ生成
    const regionRows = Object.entries(NEIGHBORHOOD_WARD_MAP).map(
      ([token, ward]) => ({
        token,
        ward,
        confidence: 100,
        source: "hardcoded",
      }),
    );

    // ③ upsert（onConflict: token / 既存レコードは上書き）
    const { error: stationError } = await supabase
      .from("station_map")
      .upsert(stationRows, { onConflict: "token" });
    if (stationError) {
      return NextResponse.json(
        { ok: false, error: `station_map upsert failed: ${stationError.message}` },
        { status: 500 },
      );
    }

    const { error: regionError } = await supabase
      .from("region_map")
      .upsert(regionRows, { onConflict: "token" });
    if (regionError) {
      return NextResponse.json(
        { ok: false, error: `region_map upsert failed: ${regionError.message}` },
        { status: 500 },
      );
    }

    // ③-b line_stations データ生成（路線×駅×順序）
    const lineStationRows: { line_name: string; station_name: string; order_idx: number }[] = [];
    for (const [lineName, stations] of Object.entries(LINE_STATION_ORDER)) {
      stations.forEach((stationName, order_idx) => {
        lineStationRows.push({ line_name: lineName, station_name: stationName, order_idx });
      });
    }

    // LINE_STATION_ORDER から削除された路線の古いDBレコードを削除
    const definedLines = Object.keys(LINE_STATION_ORDER);
    await supabase.from("line_stations").delete().not("line_name", "in", `(${definedLines.map(n => `'${n}'`).join(",")})`);

    const { error: lineError } = await supabase
      .from("line_stations")
      .upsert(lineStationRows, { onConflict: "line_name,station_name" });
    if (lineError) {
      return NextResponse.json(
        { ok: false, error: `line_stations upsert failed: ${lineError.message}` },
        { status: 500 },
      );
    }

    // ④ レスポンス
    return NextResponse.json({
      ok: true,
      station: stationRows.length,
      region: regionRows.length,
      line_stations: lineStationRows.length,
    });
  } catch (e) {
    const message = e instanceof Error ? e.message : String(e);
    return NextResponse.json({ ok: false, error: message }, { status: 500 });
  }
}
