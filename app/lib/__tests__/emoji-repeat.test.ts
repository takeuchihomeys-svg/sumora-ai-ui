// 2026-10-01 竹内「同じ絵文字を2重で使っているが、このような形に実際していない。もう一つの絵文字を使うか、絵文字を省いている」
//   YUMA に届いた2通目（AI）と、スタッフが実際に送った文（実送信・お客様の名前だけ置き換え）をそのまま使う。
import { dedupeRepeatedEmoji } from "../emoji-repeat";

let pass = 0, fail = 0;
function t(name: string, cond: boolean, note = "") { if (cond) { pass++; console.log(`  ✓ ${name}`); } else { fail++; console.log(`  ✗ ${name} ${note}`); } }

// ── YUMA 10/01 9:31 の2通目（AI）: 本文の文と内覧の誘導の締めの両方に 😊 ──
const YUMA_0931 = "お送りさせて頂きましたお部屋の中でも特にプレサンス梅田北ザ・ライブ 305号室が中津駅徒歩4分・オートロック付き・バス・トイレ別で、YUMAさんにかなりオススメ出来るお部屋となります😊！！\n\nお気に召されましたらご都合よろしいお日にちにお部屋ご案内させて頂きます😊！！";
{
  const r = dedupeRepeatedEmoji(YUMA_0931);
  t("YUMA 9:31: 内覧の誘導の締めの 😊 を外す（実送信 30/30）",
    r.text === YUMA_0931.replace("ご案内させて頂きます😊！！", "ご案内させて頂きます！！") && r.changes.length === 1 && r.changes[0].to === "", r.text);
  t("1つ目の 😊 は残す", r.text.includes("お部屋となります😊！！"));
}

// ── 申込の誘導の締めも外す（実送信 15 対 😌 1〜2）──
{
  const s = "お送りさせて頂きましたお部屋の中でも特にエスポワールⅡA 203号室が、Aさんにかなりオススメ出来るお部屋となります😊！！\n\nお気に召されましたらお申込しお部屋抑えさせて頂きます😊！！";
  const r = dedupeRepeatedEmoji(s);
  t("申込の誘導の締め: 2つ目の 😊 を外す", r.text.endsWith("お部屋抑えさせて頂きます！！") && r.text.includes("お部屋となります😊！！"), r.text);
}

// ── ご査収は 😌 に替える（実送信 😌 20 ／ なし 18 ／ 😊 1）──
{
  const s = "S-FORT桜川南 607、家賃管理費込79,000円と費用を抑えられ、白基調のお部屋でAさんにかなりオススメ出来るお部屋となります！！\n\nインターネット無料で毎月の通信費も抑えられます😊！！\n\nお手隙の際にご査収ください😊！！";
  const r = dedupeRepeatedEmoji(s);
  t("ご査収: 2つ目の 😊 → 😌", r.text.endsWith("お手隙の際にご査収ください😌！！") && r.changes[0].to === "😌", r.text);
}

// ── 3つ目も同じなら、😌 も使った後は外す ──
{
  const s = "ピックアップさせて頂きました😊！！ 初期費用も抑えられます😊！！ お手隙の際にご査収ください😊！！";
  const r = dedupeRepeatedEmoji(s);
  t("😊 → 😌 → 外す", r.text === "ピックアップさせて頂きました😊！！ 初期費用も抑えられます😌！！ お手隙の際にご査収ください！！", r.text);
}

// ── 触らない物（スタッフの実送信の形）──
