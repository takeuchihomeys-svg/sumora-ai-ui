  "ほのかさん お世話になっております！！\n新着で西中島南方周辺のエリアで2部屋オススメできるお部屋が募集中でしたのでお送りさせていただきました😊！！\n比較的初期費用も抑えられるお部屋となりますので、KITレジデンスと一緒にご査収ください😌！！",
  // 絵文字1つだけ
  "お送りさせて頂きましたお部屋の中でも特にレオンコンフォート梅田北 703号室が2020年1月築で築年数浅く、YUMAさんにかなりオススメ出来るお部屋となります！！\n\nお気に召されましたらお申込しお部屋抑えさせて頂きます😊！！",
  // お客様の表示名の絵文字（文末の飾りではない）＋文末の 😊 1つ
  "🐈‍⬛さん お世話になっております！！\n新着で一件オススメできるお部屋が募集に出ておりましたのでお送りさせていただきました😊！！\n🐈‍⬛さんお気に召されましたらご案内させて頂きます！！",
  // 物件の見出し 🌟 は数えない
  "🌟プレサンス梅田北ザ・ライブ 305\n\n家賃管理費込75,000円・御堂筋線「中津」駅徒歩4分、YUMAさんにかなりオススメ出来るお部屋となります😊！！",
  // 絵文字なし
  "かしこまりました！！\n確認させて頂きます！！",
