for (const s of KEEP) {
  const r = dedupeRepeatedEmoji(s);
  t(`触らない: ${s.replace(/\s+/g, " ").slice(0, 36)}…`, r.text === s && r.changes.length === 0, r.text);
}

// ── 言葉は1文字も消さない（絵文字を除いた文字が同じ）──
{
  const strip = (x: string) => x.replace(/\p{Extended_Pictographic}|️|‍/gu, "");
  const r = dedupeRepeatedEmoji(YUMA_0931);
  t("絵文字以外の文字は同じ", strip(r.text) === strip(YUMA_0931));
}

