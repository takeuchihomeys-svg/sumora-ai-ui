// 文は 2026-09-25 の property_customers.move_in_time の実物（234人・175種類）から形ごとに選んだ物（お客様の名前・電話番号は無い）
import { parseMoveInWant } from "../move-in-want";

let passed = 0, failed = 0;
function t(name: string, ok: boolean, extra?: unknown) {
  if (ok) { passed++; console.log(`  OK  ${name}`); } else { failed++; console.log(`  NG  ${name}${extra !== undefined ? `\n      ${JSON.stringify(extra)}` : ""}`); }
}
const TODAY = "2026-09-25";
const P = (s: string, reg = "2026-09-10") => parseMoveInWant(s, { registeredAt: reg, today: TODAY });
const by = (s: string, want: string, reg?: string) => { const w = P(s, reg); t(`「${s}」→ ${want}`, w.kind === "by" && w.wantBy === want, w); };
const kind = (s: string, k: string, reg?: string) => { const w = P(s, reg); t(`「${s}」→ ${k}`, w.kind === k && (k === "asap" ? w.wantBy === TODAY : w.wantBy == null), w); };

console.log("■ 旬・日・月だけ");
by("11月上旬", "2026-11-10");
by("11月初旬", "2026-11-10");
by("10月頭", "2026-10-10");
by("10月中旬", "2026-10-20");
by("10月下旬", "2026-10-31");
by("11月末", "2026-11-30");
by("10月", "2026-10-31");
by("11月頃", "2026-11-30");
by("10月中までに", "2026-10-31");
by("10月1日", "2026-10-01");
by("10/1", "2026-10-01");
by("10月9日", "2026-10-09");
by("2026/12/1", "2026-12-01");

console.log("■ 月が複数は一番遅い月（遅い方に合わせて LATE を出しにくく）");
by("10月~12月", "2026-12-31");
by("11.12月（安くていいとこあればすぐにでも）", "2026-12-31");
by("9月前後、余裕あれば12月", "2026-12-31", "2026-05-10");
by("10月29日〜11月1日", "2026-11-01");
by("9月中旬から下旬", "2026-09-30", "2026-08-10");
by("10月後半〜11月くらい 多少前後しても大丈夫", "2026-11-30");
by("9~11月頃(9月以降の方が良い物件が増えてきそうなら待ちたい)", "2026-11-30", "2026-06-10");

console.log("■ 年をまたぐ・来年");
by("今年12〜3月", "2027-03-31", "2026-08-10");
by("10月〜3月までには", "2027-03-31", "2026-07-10");
by("12月下旬から1月下旬にかけて", "2027-01-31", "2026-08-10");
by("来年3月までに", "2027-03-31", "2026-08-10");
by("1月", "2027-01-31");

console.log("■ 今月・来月・年内");
by("来月半ばから後半", "2026-09-30", "2026-08-10");
by("今年中", "2026-12-31", "2026-06-10");
by("年内中(12月初旬までには決めたい)", "2026-12-31", "2026-07-10");

console.log("■ すぐ＝今日（照らす時に14日の猶予）");
for (const s of ["即入居", "すぐにでも", "最短", "至急", "出来るだけ早く", "今すぐ又は1ヶ月以内", "良いところがあればすぐにでも"]) kind(s, "asap");

console.log("■ 札を付けない（目安・季節・始まりだけ・決まっていない・過ぎた日）");
for (const s of ["2ヶ月後くらい（まだ検討中）", "1ヶ月以内", "半年以内", "1、2ヶ月以内", "冬", "今年の夏頃", "秋口"]) kind(s, "vague");
for (const s of ["5月以降", "7月末〜", "9月中旬〜", "4月から"]) kind(s, "after", "2026-05-10");
for (const s of ["いつでも", "未定", "物件見つかり次第", "まだ決めていません", "21日16時希望", ""]) kind(s, "none");
kind("7月", "past", "2026-06-10");
kind("8月上旬", "past", "2026-06-10");
kind("4月か5月", "past", "2026-05-10");
kind("2024-07-24", "past", "2026-06-10");
by("3月中", "2027-03-31", "2026-05-10"); // 登録月の2か月前は来年

console.log(`\n${passed} passed, ${failed} failed`);
