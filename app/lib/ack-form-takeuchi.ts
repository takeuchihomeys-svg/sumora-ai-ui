type Env = Record<string, string | undefined>;
export function ackFormTakeuchiEnabled(env: Env = (typeof process !== "undefined" ? process.env : {}) as Env): boolean {
  // ⚠ 既定 off（入れない）: YUMA4/5 の試し（DeepSeek・受けだけの番 13番×2回・ブレインを今の番の判断に）で、これを on にすると
  //   竹内さんとの近さ 0.71→0.59・言い直し一致 73→65%・次の一手一致 81→65%（「3行」に合わせて頼まれていない中身＝申込の押し・内覧の楽しみ を真ん中に作った）。
  //   竹内さんの真ん中の1文（まだ果たしていない約束の待ちの形）は区切り1（repeat-brain-align）で出るようになった＝ここは案のまま。on で試せる
  return (env.ACK_FORM_TAKEUCHI ?? "").trim().toLowerCase() === "on";
}

