/**
 * ブレインの静的ブロック（1時間キャッシュ側）に入れる。会話に依存しないので毎回作り直さない。
 * 断定・禁止は書かない（判断はブレイン）。
 */
export function buildAixSceneNote(): string {
  const rows = Object.entries(AIX_SCENE_STATS)
    .sort((a, b) => b[1].wonPct - a[1].wonPct)
    .map(([key, s]) =>
      `- ${key}（${s.label}）｜成約側の会話 ${s.wonPct.toFixed(1)}% ／ お客様の発言から押すまで中央値 ${s.lagH.toFixed(1)}時間 ／ ${s.mode}型 ／ ${s.n}件\n`
      + `    押す直前にお客様が言っていた型: ${s.before.join(" ／ ")}\n`
      + `    押した後にお客様が返す型: ${s.after}`,
    );
  return `
【AIX が実際に押されている場面（実測180日・押下1,826件）】
お客様の言葉に**応えて**押す AIX（申込へ・内覧のご案内・待ち合わせ・物件確認した・見積書）は、
発言から中央値0.3〜2.7時間で押されていて、成約側の会話での割合も22〜43%と高い。
**こちらから**出す AIX（物件オススメ・物件送付）は発言から9〜22時間後で、成約側は14〜16%。
⚠ これは相関であって因果ではない（段階が違うだけ。まだ探している会話だから物件オススメを押している）。
  押してよい・悪いの線ではなく、「今お客様が何を求めている場面か」を読むための材料として使う。
${rows.join("\n")}
- 費用や見積もりを聞かれた時、実務では**先に募集状況の確認（物件確認した）を報告してから**見積書に進む形が多い
  （物件確認したの直前の発言に「初期費用しりたいです」「見積もりが欲しいです」が実際に並んでいる）
`;
}
