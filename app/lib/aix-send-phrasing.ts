// app/lib/aix-send-phrasing.ts
// AIX で物件を送る文（物件ピックアップ・物件オススメ）から、通常返信でしか使わない言い回しを落とす（純関数・DB 依存なし）。
//
// 2026-09-17 竹内（まりあ事例）「かしこまりました！って生成された文に入っているけど、文の構成としておかしいし、
//   全力でサポートさせて頂きます。もこれ返信の部分で使う部分なので、AIXの物件ピックアップや、物件オススメに入らない文となる」
//
// AI 生成（AIX 物件ピックアップ）:
//   「まりあさんお世話になっております！！／**かしこまりました！！**ペット可条件は外し、中央区・西区で西天満より南のエリアから
//     WIC付き1LDKでまりあさんにオススメできるお部屋ピックアップさせて頂きました！！／
//     **まりあさんにご満足頂けるお部屋が見つかるまで全力でサポートさせて頂きます！！**」
// 実送信:
//   「まりあさんお世話になっております！！／西天満より南のエリアから現在募集が出ているお部屋でまりあさんにオススメできる
//     お部屋ピックアップさせて頂きました！！／お気に召されお部屋ご案内させて頂きます！！／お手隙の際にご査収ください😌！！」
//
// 実データ（180日・スタッフ実送信）:
//   「ピックアップさせて頂きました」を含む通 362件のうち
//     「かしこまりました」…1件（0.3%）／「全力でサポート」…**0件**／「ご満足頂けるお部屋が見つかるまで」…**0件**
//     「お手隙の際にご査収ください」…291件（80%）
//   一方で「全力でサポート」は全体で 276件・「かしこまりました」で始まる通は 1007件あり、どちらも**返信**で使う言い回し。
//   ＝物件を送る通は「送りました」の報告であって、依頼の受諾（かしこまりました）や見つかるまでの宣言（全力サポート）は入らない。

/** 依頼の受諾の相槌（返信の開口語）。物件を送る通では不要 */
const RECEIPT_OPENER_RE = /^(?:かしこまりました|承知(?:いたし|し)ました|了解(?:いたし|し)ました)[！!。\s]*[😊😌✨💪]*[！!\s]*/;
/** 「見つかるまで全力でサポート」系の宣言（返信の締め）。1行まるごと落とす */
const FULL_SUPPORT_LINE_RE = /(?:見つかるまで|ご満足(?:頂|いただ)ける?(?:お部屋|物件)).{0,20}(?:全力|精一杯).{0,12}(?:サポート|お探し|探させ)|(?:全力|精一杯)で?(?:サポート|お探し)させて(?:頂|いただ)きます/;
/** 送る通の締め（実送信 80%）。返信専用の締めを落として締めが無くなった時だけ足す */
export const SEND_CLOSER_LINE = "お手隙の際にご査収ください😌！！";
/** 既に締めがあるか（ご査収・ご案内の申し出・申込の誘導） */
const HAS_CLOSER_RE = /ご査収|ご案内させて(?:頂|いただ)きます|お申込|抑えさせて(?:頂|いただ)きます|如何でしょうか|いかがでしょうか/;

/**
 * 物件を送る通から返信専用の言い回しを落とす。
 * ・行頭の「かしこまりました！！」は落とす（同じ行に本題が続く時は相槌だけ落として本題を残す）
 * ・「〜見つかるまで全力でサポートさせて頂きます」の行はまるごと落とす
 * ・落とした結果、締めが無くなったら「お手隙の際にご査収ください😌！！」を足す（実送信 80% の締め）
 * 物件カード（🌟で始まる本文）には掛けない＝呼び出し側で送付文の本文だけに使う
 */
export function stripReplyOnlyPhrases(text: string, opts: { addCloser?: boolean } = {}): string {
  const src = text ?? "";
  if (!src.trim()) return src;
  const kept: string[] = [];
  let changed = false;
  for (const line of src.split("\n")) {
    if (FULL_SUPPORT_LINE_RE.test(line)) { changed = true; continue; }   // 行ごと落とす
    const stripped = line.replace(RECEIPT_OPENER_RE, "");
    if (stripped !== line) {
      changed = true;
      if (!stripped.trim()) continue;   // 「かしこまりました！！」だけの行は消す
      kept.push(stripped);
      continue;
    }
    kept.push(line);
  }
  if (!changed) return src;
  let out = kept.join("\n").replace(/\n{3,}/g, "\n\n").trim();
  if (!out) return src;   // 全部落ちたら元のまま（安全側）
  // 締めを足すのは物件ピックアップ（送付文）だけ。物件オススメ（🌟の物件カード）は
  // 「お手隙の際にご査収ください」を使わない決まり（AIX_PROPERTY_RECOMMENDATION_RULES）なので足さない
  if (opts.addCloser !== false && !HAS_CLOSER_RE.test(out)) out += `\n\n${SEND_CLOSER_LINE}`;
  return out;
}

