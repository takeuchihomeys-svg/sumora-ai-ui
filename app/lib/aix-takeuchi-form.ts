/** 希望条件がある時の②の条件ルール（conditionsRule の置き換え） */
export function takeuchiPickupConditionsRule(): string {
  return `・②の形は竹内さんの送信の多数派: 「[エリア]周辺全域から[お客様名]にオススメできる[条件]のお部屋ピックアップさせて頂きました😊！！」
  条件の入れ方（厳守）：
  ・エリアは必ず入れる（「〇〇周辺全域から」。エリアの言い方は会話・希望条件の文字のまま）
  ${pickupCondCountOn() ? deliveredPickupConditionRule(null).replace(/^・/, "・") + "。無理に足さない" : "・条件は入れても2つまで（竹内さんは0〜2つが8割強・エリアだけの形が一番多い）。お客様が特に気にしていた条件（家賃の上限・ペット・駐車場・広さ・二人暮らし・初期費用 等）を優先し、無理に足さない"}
  ・入居日はお客様から必須指定がある場合のみ入れる（指定がなければ入れない）
  ・「ご希望のご条件に合ったお部屋」は使わない。条件を書かない時は「[お客様名]にオススメできるお部屋」か「[お客様名]ご希望のご条件に近いお部屋」
  ・条件の語は【お客様の希望条件】の欄の文字のまま書く（言い換えない・欄に無い条件を作らない）
  竹内さんが送った行（言い回しの手本・エリアと条件はその時の物なので写さない）:
${TAKEUCHI_PICKUP_LINE_EXAMPLES.map((e) => `  「${e}」`).join("\n")}`;
}

/**
 * 物件ピックアップの固定の型（sendSystem）の②の指示と出力例を竹内さんの形に置き換える（決定論・文字列の置き換えだけ）。
 *   ・「（エリア必須・最大4個）」→ 2つまで ／ 新着の「エリアと間取りは必ず」「最大4個まで（エリア・間取りの2つは必ず含む）」→ エリア＋2つまで
 *   ・②の型「〇〇から[お客様名]ご希望の〜なお部屋」→「〇〇周辺全域から[お客様名]にオススメできる〜のお部屋」
 *   ・出力例の「…周辺から〇さんご希望のご条件に合ったお部屋ピックアップ…」→「…周辺全域から〇さんにオススメできるお部屋ピックアップ…😊！！」
 */
export function takeuchiPickupSystem(system: string): string {
  let s = String(system ?? "");
  s = s.split("具体条件（エリア必須・最大4個）を文中に織り込むこと").join(pickupCondCountOn() ? "具体条件（エリア必須・条件の数は決め打ちしない＝お客様が特に気にしていた条件だけ・エリアだけでもよい）を文中に織り込むこと" : "具体条件（エリア必須・条件は入れても2つまで・エリアだけでもよい）を文中に織り込むこと");
  s = s.split("「〇〇から[お客様名]ご希望の〜なお部屋ピックアップさせて頂きました！！」").join("「〇〇周辺全域から[お客様名]にオススメできる〜のお部屋ピックアップさせて頂きました😊！！」");
  s = s.split("・エリアと間取りは必ず入れる（両方必須・省略不可）").join("・エリアは必ず入れる（間取りはお客様が特に気にしている時だけ）");
  s = s.split("・入れる条件は最大4個まで（エリア・間取りの2つは必ず含む）。箇条書きにせず文中に自然に埋め込む").join(
    `${pickupCondCountOn() ? "・条件の数は決め打ちしない（竹内さんの新着の行は条件0〜1つが多い・お客様が特に気にしていた条件だけ）" : "・条件はエリアの他に入れても2つまで（竹内さんの新着の行は条件0〜1つが多い）"}。箇条書きにせず文中に自然に埋め込む\n・竹内さんが送った新着の行（言い回しの手本）: ${TAKEUCHI_NEW_ARRIVAL_LINE_EXAMPLES.map((e) => `「${e}」`).join(" ")}`);
  s = s.split("例：「新着で梅田まで30分圏内のエリアから[お客様名]にオススメできる2LDK・2口ガスコンロ付きの9/1入居可能なお部屋が3件募集にでました！！」").join("例：「新着で梅田まで30分圏内のエリアから[お客様名]にオススメできる2LDKのお部屋が3件募集にでました！！」");
  s = s.split("新着で梅田まで30分圏内のエリアから[お客様名]にオススメできる2LDK・2口ガスコンロ付きのお部屋が[新着件数]募集にでました！！").join("新着で梅田まで30分圏内のエリアから[お客様名]にオススメできる2LDKのお部屋が[新着件数]募集にでました！！");
  s = s.replace(/(大阪駅・難波駅|梅田・難波)周辺から(Rさん|\[お客様名\])ご希望のご条件に合ったお部屋ピックアップさせて頂きました！！/g, "$1周辺全域から$2にオススメできるお部屋ピックアップさせて頂きました😊！！");
  return s;
}
