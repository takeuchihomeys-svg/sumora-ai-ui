/** ピックアップ行を竹内さんの形にするか（AIX_TAKEUCHI_FORM が on の上で・AIX_TAKEUCHI_PICKUP=off でこの部分だけ旧に） */
export function aixTakeuchiPickupOn(env: Record<string, string | undefined> = process.env): boolean {
  return aixTakeuchiFormOn(env) && (env.AIX_TAKEUCHI_PICKUP ?? "on").trim() !== "off";
}

