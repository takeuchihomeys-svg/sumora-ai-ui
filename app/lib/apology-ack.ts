// app/lib/apology-ack.ts
// お客様が謝った時の受け止め（純関数・DB 依存なし）。
//
// 2026-09-17 竹内（慶次事例）「ここでかしこまりましたは文としておかしいし、ここはお客さん受け入れる。全然です！等」:
//   慶次 17:07 こちら「かしこまりました！！／敷金礼金無しのお部屋で審査通過しやすい独立系保証会社採用のオススメできるお部屋探させていただきます！！」
//   → 17:40 お客様「本当にご無理を言いまして申し訳ありません。／よろしくお願い致します。」
//   → AI 下書き「**かしこまりました！！**／敷礼なしのお部屋で…ピックアップさせて頂きます！！」
//   お客様は新しい依頼をしておらず**謝っている**だけなので、「かしこまりました」（依頼の受諾）では受け止めになっていない。
//
// 実データ（365日・実送信）: 「とんでもございません」で始まる 16通・「全然大丈夫です」12通・「お気になさらず」2通。
//   同じ慶次さんの会話でも、過去に「ご無理を言いますが、よろしくお願い致します。」→
//   「**とんでもございません😊！！**／慶次さんにオススメできるお部屋ピックアップ出来次第お送りさせて頂きます！！」と返している。
//   一方「かしこまりました」で始まるのは、謝罪と一緒に**依頼**が来た時（「すいません、条件が追加でありまして…保証人不要も追加でお願いします」
//   「沢山送ってしまって申し訳ないです！こちらの6件お調べして頂きたい」）＝受諾の言葉。謝罪だけの時とは場面が違う。

/** 謝罪の語（お客様の発言に出る形） */
const APOLOGY_RE = /申し訳|ご無理|無理(?:を)?(?:言|申)|すみません|すいません|ごめんなさい|お手数(?:おかけ|をおかけ)|恐縮/;
/**
 * 新しい依頼（これがあれば「かしこまりました」で受ける場面＝謝罪だけではない）。
 * 「よろしくお願い致します」「お願いします」は結びの挨拶なので依頼に数えない
 */
//   （「お調べして頂きたい」「キャンセルさせていただきたい」のように間に語が挟まるので 0〜6字の隙間を許す）
const REQUEST_RE = /(?:確認|調べ|探し|送っ|お送り|教え|見たい|内覧|申込|申し込|変更|追加|キャンセル|やめ|止め)[^\n。！!]{0,6}(?:頂|いただ|ほし|欲し|下さ|ください|たい|ませんか|できま|可能)|も追加|条件(?:を)?(?:追加|変更)|こちらも|この(?:物件|お部屋)|ありますか|可能でしょうか|如何でしょうか|でしょうか？/;

export type ApologyVerdict = { apology: boolean; reason: string };

/**
 * お客様が「謝っているだけ」か（新しい依頼が無い）。
 * 依頼が一緒に来ている時は false＝従来どおり「かしこまりました」で受ける
 */
export function resolveApologyOnly(customerText: string | null | undefined): ApologyVerdict {
  const t = (customerText ?? "").trim();
  if (!t) return { apology: false, reason: "no_text" };
  if (!APOLOGY_RE.test(t)) return { apology: false, reason: "no_apology" };
  if (REQUEST_RE.test(t)) return { apology: false, reason: "has_request" };
  // 2026-10-02 竹内「初期のころ制約かけまくっていたので、理想の文がぶつかってしまって…そこもみつける」:
  //   人の実送信（60日・scripts/audit-exits-vs-human.ts）をこの出口に通すと、スタッフの「かしこまりました！！」を
  //   「とんでもございません😊！！」に書き換えた通が 27通あった。全部「すみません＋お知らせ・ご希望」だった:
  //     「すみません15分遅れます」→「かしこまりました！！お気をつけてお越しください」（遅れの連絡 10通以上・全部 かしこまりました）
  //     「すみません、いったんキャンセルでお願いいたします」「ごめんなさい収納少ないので一旦なしで」「マックス7.5が希望です」
  //   ＝「すみません」は前置きで、お客様は新しい事を伝えている（受け止めではなく受諾の場面）。
  //   線（実送信 180日・お客様の発言から謝罪・挨拶・結び・絵文字を除いて残る字数）:
  //     残り 0〜4字 … 受け止め（とんでもございません／全然です）13・かしこまりました 0
  //     残り 5字〜  … かしこまりました 35 が出始める（最初は「少し遅れます」6字）
  //   → 残りが4字以下（謝っているだけ）の時だけ「謝っているだけ」とする（入口の材料も出口の置き換えも同じ線）。
  //   慶次事例「本当にご無理を言いまして申し訳ありません。／よろしくお願い致します。」は残り3字（本当に）で従来どおり。
  if (apologyResidual(t).length > APOLOGY_RESIDUAL_MAX) return { apology: false, reason: "has_content" };
  return { apology: true, reason: "apology_only" };
}

/** 謝っているだけと見なす残りの字数の上限（上の線） */
export const APOLOGY_RESIDUAL_MAX = 4;
/**
 * お客様の発言から、謝罪・お手数・わがまま・挨拶・結び・お礼・絵文字・記号を除いた残り（＝新しく伝えている中身）。
 * 純関数。線の測り方は scripts/audit-exits-vs-human.ts と同じ材料（2026-10-02）
 */
export function apologyResidual(text: string): string {
  return (text ?? "")
    .replace(/https?:\/\/\S+/g, "")
    .replace(/\[(?:スタンプ|画像)\]/g, "")
    .replace(/\p{Extended_Pictographic}|[‍️⁣]|[（(][^）)]{0,8}[）)]/gu, "")
    // 謝る理由（こちらに手間をかけた事）は中身ではない: 「ぽろぽろ質問してしまってすみません」「注文が多くてすみません」「手間ばかりおかけして申し訳ない」
    //   （実送信ではどれも「全然です／とんでもございません」で受けている）
    .replace(/[^\s、。！!？?\n]{0,14}?(?:てしまって|てしまい|でしまって|多くて|ばかり[^\s、。！!]{0,8}て)[、,…\s]*(?=(?:本当に)?(?:申し訳|すみません|すいません|ごめん))/g, "")
    .replace(/(?:本当に|大変|何度も|色々と?|いろいろ|直前の連絡となって|ご連絡|返信|お返事|対応)?(?:遅くな(?:り|って)|おそくな(?:り|って))?(?:申し訳(?:ない|ありません|ございません|御座いません)(?:です|でした)?|すみません(?:でした)?|すいません(?:でした)?|ごめんなさい)/g, "")
    .replace(/(?:ご無理を?(?:言|申)(?:いまして|ってしまい|いますが|ってすみません)?|お手数(?:を)?(?:おかけ|お掛け|かけ)(?:します|しますが|しており|してしまい|ますが)?|わがまま(?:を言いますが|になってしまい|ですみません)?|ワガママになってしまい|恐縮(?:です|ですが)?)/g, "")
    .replace(/(?:何卒|引き続き|今後とも)?(?:よろしく|宜しく)お願い(?:します|いたします|致します|申し上げます)|お願いします|ありがと(?:う)?ございます|お世話にな(?:って|り)(?:おります|ます)|こちらこそ|承知(?:いたし|致し|し)ました|かしこまりました|了解(?:です|しました)/g, "")
    .replace(/[\s、。！!？?…・,.\-~〜ー💦]+/g, "");
}

/** 受け止めの一言（実送信で一番多い形）。絵文字は出口の設定で落ちる */
export const APOLOGY_ACK_LINE = "とんでもございません😊！！";
/** 既に受け止めになっている開口語（置き換えない） */
const ALREADY_ACK_RE = /^(?:とんでもございません|とんでもない|全然(?:大丈夫|です|問題)|お気になさら|お気になさらず|大丈夫です)/;
/** 置き換える開口語（依頼の受諾・相槌。1行だけの時に限る） */
// 2026-10-02: 「はい」は置き換えない。謝っているだけの発言（上の線の内側）にスタッフが「はい😊！！」で返した実送信が3通あり
//   （「お手数おかけしてしまいすみません！」→「はい😊！！無事ご入居頂けますよう…」）、受諾の「かしこまりました」は0通＝直すのは かしこまりました の側だけ
const RECEIPT_OPENER_RE = /^(?:かしこまりました|承知(?:いたし|し)ました|了解(?:いたし|し)ました)[！!。\s]*[😊😌✨]*[！!\s]*$/;

/**
 * 謝罪を受けた返信の冒頭を受け止めの言葉にする。
 * ・先頭行が「かしこまりました！！」だけ（依頼の受諾）なら「とんでもございません😊！！」に置き換える
 * ・既に受け止めの言葉なら触らない。挨拶行（〇〇さんお世話になっております）の後にある時もその次の行を見る
 * ・先頭行に本題が続いている時（「かしこまりました！！6件確認します」）は触らない＝受諾として正しい場面
 */
export function ensureApologyOpener(text: string, apology: boolean): string {
  const src = text ?? "";
  if (!apology || !src.trim()) return src;
  const lines = src.split("\n");
  // 挨拶行（お世話になっております・お待たせ致しました）は飛ばす
  let i = 0;
  while (i < lines.length && /(?:お世話になっております|お待たせ(?:致しました|しました)|ご連絡(?:頂き|いただき)ありがとうございます)/.test(lines[i])) i++;
  if (i >= lines.length) return src;
  const head = lines[i].trim();
  if (ALREADY_ACK_RE.test(head)) return src;
  if (!RECEIPT_OPENER_RE.test(head)) return src;
  lines[i] = APOLOGY_ACK_LINE;
  return lines.join("\n");
}

/** 生成の材料（この場面では受け止めから入る）。場面でなければ空 */
export function buildApologyNote(apology: boolean): string {
  if (!apology) return "";
  return [
    "",
    "",
    "【お客様が謝っている場面（受け止めから入る）】お客様は新しいご依頼ではなく「ご無理を言って申し訳ない」と謝っています。",
    `冒頭は「かしこまりました」（依頼の受諾）ではなく受け止めの一言（「${APOLOGY_ACK_LINE}」「全然大丈夫です😊！！」）から入り、`,
    "そのうえで、こちらが約束していること（お部屋のピックアップ・確認）を続けること。",
  ].join("\n");
}
