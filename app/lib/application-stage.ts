// app/lib/application-stage.ts
// 「このお客様の申込がどこまで進んでいるか」を会話から決める（純関数・DB 依存なし）。
//
// 2026-09-21 竹内「先ほどの実際に申し込んだかのところ判断できるようにする。
//   そしてそれに派生する他の状況把握で弱い部分も見つけ出して補っていく。実際のスタッフのように」
//
// ■ なぜ要るか
//   LedgerFacts には `applicationGuided`（AIX【申込へ】を押した＝**案内した**）しか無く、
//   「**実際に申し込んだか**」を表す項目が無かった。
//   材料に「申込は済んでいない」が無いので、LLM が想像で埋める余地がある
//   （実物: 物件の詳細を送った直後の「検討します」に「お申込みいただきありがとうございます」）。
//   設計知見「材料が空の時ほど LLM は会話から拾って埋める」。
//
// ■ 実測（scripts/audit-application-submitted.ts・直近365日・スタッフ送信12,207通）
//     ① これから申し込む宣言   160通（1.3%）「〇〇お申込みさせていただきます😊！！」
//     ② 申込の情報を依頼       223通（1.8%）「こちらお申込に必要なご情報となります😊！！」「【緊急連絡先欄】」
//     ③ 申込完了・確認中       112通（0.9%）「無事一番手にてお申込み完了しております！！」
//     ④ 審査                   206通（1.7%）「保証会社審査通過後オーナーによる最終審査に移ります。」
//   会話単位では 86/346件（24.9%）に申込に進んだ形がある。
//   `conversations.status` と突き合わせると**取りこぼしは5件だけ**（status 側が先に進んでいる分）。
//
// ■ ⚠ いちばん大事な区別: **他人の申込**
//   実測の③に「1番手でお申込みがはいっておりますので、2番手以降でのお申込みとなります。」が4回混ざっていた。
//   これは**他のお客様が申し込んだ**という物件確認の結果で、このお客様の申込ではない。
//   「2番手以降」「お申込みが入っており」は他人の印なので、**先に外す**。

/** 申込の進み具合（後ろほど進んでいる） */
export type ApplicationStage =
  | "none"            // 申込の話が出ていない
  | "guided"          // こちらが申込を案内した（お気に召されましたらお申込み…）
  | "declared"        // こちらが「申し込みます」と宣言した
  | "info_requested"  // 申込に必要な情報（緊急連絡先・勤務先）を依頼した
  | "submitted"       // 申込を入れ終えた（完了の報告）
  | "screening";      // 審査に進んでいる

export type ApplicationVerdict = {
  stage: ApplicationStage;
  /** 実際に申し込んだと言えるか（submitted 以上） */
  submitted: boolean;
  /** 何を根拠にしたか（監査・ログ用・60字） */
  evidence: string | null;
};

/**
 * ⚠ **他人の申込**の印。これがある行は、このお客様の申込としては数えない。
 *   実送信: 「1番手でお申込みがはいっておりますので、2番手以降でのお申込みとなります。」
 *          「現在お申込みが入っており、3番手でのお申込みが可能となっております！！」
 */
export const OTHERS_APPLICATION_RE = new RegExp([
  "[23４-９]番手", "[二三四]番手",
  "お?申込(?:み|)が(?:入|はい)って(?:おり|しまい|い|ます)",
  "申込(?:み|)(?:が)?入る可能性", "お申込(?:み|)を停止",
  // 2026-09-21 2周目の監査: 「1番手審査の方否決・キャンセルの場合、繰り上がり審査開始」＝**他人の審査**
  "[0-9０-９]番手(?:の方|審査の方|の審査)", "繰り上がり",
].join("|"));

/**
 * ⚠ **審査の一般論・制度の説明**。これがある行は「審査に進んでいる」として数えない。
 *
 * 2026-09-21 全件監査（scripts/audit-application-stage-accuracy.ts）で見つけた誤判定:
 *   「審査**通過しやすい**お部屋ピックアップしお送りさせていただきます」← 物件の特徴（申込していない）
 *   「審査通過する為に独立系の保証会社を中心に…」                    ← 探し方の方針
 *   「※保証会社審査**通過後**オーナー審査移行までキャンセル可能です」  ← 制度の説明
 *   「お部屋お申込みを行なってから、ご入居の審査が3日〜10日程必要」    ← 制度の説明
 *   「無事審査通過**しますよう**サポートさせて頂きます」              ← 願望
 *   これらを数えると、物件を探している段階の会話が「審査中」になる（80件中の多くがこれだった）。
 */
export const SCREENING_GENERAL_RE = new RegExp([
  // 「審査通過しやすいお部屋」＝ 物件の特徴・探し方の方針
  "審査(?:が|に)?(?:通過|通り)?(?:し)?やす", "通しやす",
  "審査通過(?:する為|するため|しますよう|するよう|できるよう|出来るよう)",
  // 制度の説明（〜後にキャンセル可・契約に移る・日数）
  "審査(?:通過|否決)?後[^\\n。！!]{0,20}(?:キャンセル|移行|契約|お手続き)",
  "審査が?[0-9０-９]{1,2}\\s*[日週]",
  // 2026-09-21 2周目の監査で足した分:
  //   「審査通過しましたらご入居出来る」＝ **仮定**（まだ申し込んでいない）
  "審査(?:通過|が通過)?し(?:ま)?(?:したら|たら)", "審査(?:に)?通れば",
  //   「お気に召されましたら一度審査かけさせて頂きます」＝ **提案**（まだ）
  "お気に召され[^\\n。！!]{0,24}審査", "審査(?:を)?かけ(?:させて|ます|る)",
  //   「審査開始は8/17日からとなります」＝ 予定の説明
  "審査開始は",
].join("|"));

/** ④ 審査に進んでいる（このお客様の審査が動いている形だけ） */
export const SCREENING_RE = /審査(?:中|に進|に移|開始)|審査結果|審査(?:通過|否決)(?:し(?:ました|ており)|となり|との|いたしました)|審査(?:を)?進め(?:て|させて)/;
/** ③ 申込を入れ終えた（完了の報告）。「1番手で」はこちらのお客様の申込を指す形でだけ使う */
export const SUBMITTED_RE = /お?申込(?:み|)完了|お?申込(?:み|)入れ(?:させて|ました)|(?:1|一)番手[^\n。！!]{0,10}お?申込(?:み|)(?:完了|出来|でき)|お部屋(?:を)?(?:抑え|押さえ)(?:させて(?:頂|いただ)きました|ました)/;
/** ② 申込に必要な情報の依頼 */
export const INFO_REQUESTED_RE = /お申込(?:み|)に(?:必要|あたり)|【緊急連絡先欄】|申込書/;
/** ① これから申し込む宣言 */
export const DECLARED_RE = /お?申込(?:み|し|)(?:させて(?:頂|いただ)きます|します|いたします)|お申込み?手続き(?:を)?進め/;
/** 申込を案内した（まだ申し込んでいない。「お気に召されましたら」が付く形） */
export const GUIDED_RE = /お気に召され[^\n。！!]{0,20}お?申込|お?申込(?:み|)(?:で|し)[^\n。！!]{0,10}お部屋(?:を)?(?:抑え|押さえ)|お?申込(?:み|)(?:いただ|頂)け(?:ます|る)/;

/** 段階の強さ（比較用） */
const RANK: Record<ApplicationStage, number> = {
  none: 0, guided: 1, declared: 2, info_requested: 3, submitted: 4, screening: 5,
};

/**
 * こちらの発言から、このお客様の申込がどこまで進んでいるかを決める。
 *
 * ⚠ 他人の申込の行（2番手以降・申込が入っており）は**先に外す**。
 *   外さないと、物件確認の結果報告で「申込済み」と誤判定する。
 * ⚠ 行ごとに見る。1通に「他人の申込」と「こちらの申込」が混ざることがあるため。
 *
 * @param staffTexts こちらの発言（古い順・新しい順どちらでもよい）
 */
export function resolveApplicationStage(staffTexts: ReadonlyArray<string | null | undefined>): ApplicationVerdict {
  let best: ApplicationStage = "none";
  let evidence: string | null = null;
  const bump = (s: ApplicationStage, line: string) => {
    if (RANK[s] > RANK[best]) { best = s; evidence = line.trim().slice(0, 60); }
  };
  for (const raw of staffTexts) {
    const text = (raw ?? "").trim();
    if (!text) continue;
    for (const line of text.split("\n")) {
      const l = line.trim();
      if (!l) continue;
      // 他人の申込の行はこのお客様の申込として数えない
      if (OTHERS_APPLICATION_RE.test(l)) continue;
      // 審査の一般論・制度の説明の行も数えない（「審査通過しやすいお部屋」は物件の特徴）
      if (!SCREENING_GENERAL_RE.test(l) && SCREENING_RE.test(l)) bump("screening", l);
      if (SUBMITTED_RE.test(l)) bump("submitted", l);
      if (INFO_REQUESTED_RE.test(l)) bump("info_requested", l);
      if (DECLARED_RE.test(l)) bump("declared", l);
      if (GUIDED_RE.test(l)) bump("guided", l);
    }
  }
  return { stage: best, submitted: RANK[best] >= RANK.submitted, evidence };
}

/**
 * 生成に渡す材料。**申込が済んでいない時こそ書く**（材料が空だと LLM が埋めるため）。
 * 済んでいる時は「どこまで進んだか」を伝える。
 */
export function buildApplicationStageNote(v: ApplicationVerdict): string {
  switch (v.stage) {
    case "none":
      return "\n\n【申込の状況】このお客様はまだお申込みをされていない（申込の話も出ていない）。"
        + "「お申込みいただきありがとうございます」のような**申込が済んだ前提の文は書かない**。";
    case "guided":
      return "\n\n【申込の状況】こちらが「お気に召されましたらお申込み」と**案内しただけ**で、まだお申込みはされていない。"
        + "「お申込みいただきありがとうございます」のような**申込が済んだ前提の文は書かない**。";
    case "declared":
      return "\n\n【申込の状況】こちらが「お申込みさせて頂きます」と**申込を入れると宣言した**段階。"
        + "まだ完了の報告はしていないので「お申込み完了しました」とは書かない。";
    case "info_requested":
      return "\n\n【申込の状況】申込に必要なご情報（緊急連絡先など）をお願いしている段階。"
        + "情報が届いたお礼は書いてよいが、審査の結果・可否は書かない。";
    case "submitted":
      return "\n\n【申込の状況】**お申込みは完了している**。お礼や申込後の進み方（審査の進捗のご連絡）を書いてよい。"
        + "新しい物件の提案・内覧の提案は書かない。";
    case "screening":
      return "\n\n【申込の状況】**審査に進んでいる**。結果・可否・日数は断言せず「進捗あり次第ご連絡させて頂きます」に留める。";
  }
}
