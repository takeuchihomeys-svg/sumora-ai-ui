// app/lib/application-status-note.ts
// AIX【物件確認した】で「どの物件が申込ありか」を文にする（純関数・DB 依存なし）。
//
// 2026-09-21 竹内「申込ありボタンは物件毎につける。そうすれば、どの物件が申込ありなのか判断できるから。
//   また他に必要な改善あれば教えて。実際の文使いやすいように」
//
// ■ 今どうなっていたか（コードと実測）
//   入力が**2か所**あった:
//     ① 全体の「申込状況」（available_application = "yes"/"no"）… 物件カードの**上**
//     ② 物件ごとの「募集状況」（prop_statuses[i] = "unavailable"＝申込あり）… 物件カードの**中**
//   そして aix/action は、物件ごとのステータスが入っていれば①を**無視**する作りだった
//   ＝ 画面に出ているのに効かないボタンがあった（設計知見「同じ事実に数え方が2つあると…」）。
//   さらに複数件の時の出力は箇条書きの注記 `・〇〇 202号室　※ 申込あり` だけで、
//   **実送信365日で「※ 申込あり」の形は 0件**だった。
//
// ■ スタッフが実際に書いている形（実送信そのまま）
//   ・全部が申込あり:
//       「お送り頂きました2部屋とも現在お申込がはいっております！！
//        既に1番手のお申込が入っておりますので、お申込頂ける場合は2番手以降でのご案内となります！！」
//   ・一部が申込あり（どの物件かを**名指しする**）:
//       「1枚目の栄美グランドハイツはお申込がはいっておりますので、
//        1番手の方がキャンセルになった際に繰り上がる2番手以降でのお申込となります！！」
//       「・SHANNON は既に1件お申込みが入っており2番手以降でのお申込みが可能です！！」
//   ・1件だけ:
//       「LOHAS豊中稲津町現在1番手でお申込みが入っており審査中となります！
//        お申込みされる際は2番手以降でのお申込みとなります！！」
//   ＝ 竹内さんの言う「どの物件が申込ありなのか判断できる」は、**名指し＋2番手の説明**で実現されている。
//
// ⚠ 「審査中となります」は実送信にあるが**こちらで事実を確かめていない**ので作らない
//   （設計知見「データにない文を作らない」。申込が入っている＝審査中とは限らない）。

/** 物件1件分（申込ありかどうかの判断に使う最小の情報） */
export type PropertyForNote = {
  /** 物件名（号室まで含む形。空なら「物件①」等の代わりの名前が入る） */
  name: string;
  /** 画面の募集状況。unavailable＝申込あり */
  status: string;
};

/** 申込ありか */
export function isApplied(status: string | null | undefined): boolean {
  return (status ?? "").trim() === "unavailable";
}

/**
 * 申込ありの物件について、スタッフの実送信の形で1ブロック作る。
 * 申込ありが1件も無ければ空文字。
 *
 * @param props     この通で扱う物件（並びは画面と同じ）
 * @param opts.total 「送って頂いた〇部屋」の〇。省略時は props.length
 */
export function buildApplicationNote(
  props: ReadonlyArray<PropertyForNote>,
  opts: { total?: number } = {},
): string {
  const applied = props.filter((p) => isApplied(p.status));
  if (applied.length === 0) return "";
  const total = opts.total ?? props.length;

  // 全部が申込あり（実送信:「お送り頂きました2部屋とも現在お申込がはいっております！！」）
  if (applied.length === total && total > 1) {
    return `お送り頂きました${total}部屋とも現在お申込がはいっております！！\n`
      + `既に1番手のお申込が入っておりますので、お申込頂ける場合は2番手以降でのご案内となります！！`;
  }

  // 1件だけ（実送信:「〇〇 …お申込みが入っており／お申込みされる際は2番手以降でのお申込みとなります！！」）
  if (total === 1 || (applied.length === 1 && props.length === 1)) {
    const n = applied[0].name.trim();
    return `${n ? `${n}` : "こちらのお部屋"}既にお申込みが入っております！！\n`
      + `お申込みされる際は2番手以降でのお申込みとなります！！`;
  }

  // 一部が申込あり（実送信:「〇〇はお申込がはいっておりますので、1番手の方がキャンセルになった際に繰り上がる2番手以降でのお申込となります！！」）
  //   ⚠ **どの物件かを名指しする**のが竹内さんの狙い。名前が空の物は名指しできないので「こちらのお部屋」にする
  const names = applied.map((p) => p.name.trim()).filter(Boolean);
  if (names.length === 0) {
    return `お申込みが入っているお部屋が${applied.length}部屋御座います！！\n`
      + `1番手の方がキャンセルになった際に繰り上がる2番手以降でのお申込となります！！`;
  }
  const subject = names.length === 1 ? names[0] : names.join("・");
  return `${subject}はお申込がはいっておりますので、\n`
    + `1番手の方がキャンセルになった際に繰り上がる2番手以降でのお申込となります！！`;
}

/**
 * 箇条書きの行に付ける注記。
 *
 * ⚠ 実送信365日で `※ 申込あり` の形は **0件**。スタッフは箇条書きの注記ではなく
 *   本文で名指しして説明する（buildApplicationNote）。
 *   ただし箇条書きの中でも「どれが申込ありか」は見えた方がよいので、
 *   注記は**残すが言い方を実送信に寄せる**（「※ お申込あり」ではなく「※ 申込済み」でもなく、
 *   実送信にある「お申込がはいっております」の短い形）。
 */
export function applicationBulletNote(status: string | null | undefined): string {
  return isApplied(status) ? "　※ お申込みが入っております" : "";
}
