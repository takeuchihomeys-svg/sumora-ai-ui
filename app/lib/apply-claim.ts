// 「お申込み情報を受け取りました」型の捏造を落とす（純関数・DB 依存なし）。
//
// 2026-09-20 竹内（S さん事例）
//   「まだ申込情報の意味不明なのが出ている。**申込情報は申込のフォーマットの部分となる**」
//   「申込情報は AIX の申込へ からフォーマット送ってきた後にくるものやから、そこも踏まえれたら
//     この変なミスもさらにおさえられる」
//
// 【実物】status=viewing・is_post_apply=false・申込フォーマットを**一度も送っていない**会話で、
//   お客様「ありがとうございます！考えます(よろしく)」に対して
//   AI「はい！！\nお申込み情報を確かに受け取りました😊！！\n私の方でもオススメできるお部屋が…」
//   ブレインの方向は「感謝を受け取り検討を見守る姿勢で締める」＝**正しかった**。
//   後半（随時ピックアップしてお送り）も PS_THINKING の正解形。**冒頭の1文だけが捏造**。
//
// 【竹内さんの言う「申込情報」の正体】AIX【申込へ】が送る**申込フォーマット**のこと。
//   実送信の定型（150通）:
//     「こちらお申込に必要なご情報となります😊！！
//      上記フォーマットご入力いただき、ご本人確認書類として運転免許証またはマイナンバーカードの
//      裏表の写真をお送りください！！ お送り頂き次第、お部屋お申込し抑えさせて頂きます！！」
//   お客様がそれを記入して返した時が「申込情報が届いた」場面。
//
// 【線】scripts/audit-apply-format-flow.ts:
//   ・「申込の情報を受け取った」型は実送信365日 **12,046通中 0通**（＝誤削除0）
//   ・記入が返ってきた時のスタッフの正解は全部「**お送りいただきありがとうございます**」型で、
//     「受け取りました」とは**誰も書かない**。つまりこの言い回しは正しい場面でも不要。
//   → 台帳を見るまでもなく**無条件で落として安全**。

/** 「申込の情報・内容を受け取った／受領した」と述べる形（実送信0通）
 *  2026-09-20 竹内（YUMA 本番検証）: 「お申込みの**ご意思承りました**」も足した。
 *  実送信365日 12,048通で **0通**（正解は「お申込みさせていただきます」147通）。
 *  「承りました」単体は7通あるので落とさない（「内覧のキャンセル承りました」等は正しい使い方）。 */
export const APPLY_RECEIVED_RE =
  /お?申込(?:み)?(?:の)?(?:情報|内容|書類)?[^\n。！!？?]{0,10}(?:を)?(?:確かに)?(?:受け取り|受領|拝受)(?:(?:いた|致)?し)?(?:まし)?た|お?申込(?:み)?(?:情報|内容)[^\n。！!？?]{0,8}(?:頂きました|いただきました)|お?申込(?:み)?(?:の)?ご意思[^\n。！!？?]{0,6}(?:承り|受け(?:取り)?|頂き|いただき)(?:まし)?た/;

/** 落とした後に残る文が「お客様への返信」として成り立つ最小の長さ */
const MIN_REMAIN = 6;

/**
 * 「お申込み情報を受け取りました」型の1文だけを落とす（本文の他は1文字も変えない）。
 * 行単位で見るのは、実物が独立した1行として現れるから（「はい！！\n**お申込み情報を確かに受け取りました😊！！**\n私の方でも…」）。
 * 行の中に混ざっている時は文単位で落とす。
 */
export function stripApplyReceivedClaim(text: string): { text: string; removed: string[] } {
  if (!text) return { text, removed: [] };
  const removed: string[] = [];
  const outLines: string[] = [];
  for (const line of text.split("\n")) {
    if (!APPLY_RECEIVED_RE.test(line)) { outLines.push(line); continue; }
    // 行の中の「文」だけを落とす（。！!？? で区切る。絵文字は文末に残る）
    const parts = line.split(/(?<=[。！!？?])(?![。！!？?])/);
    const kept = parts.filter((s) => {
      if (!APPLY_RECEIVED_RE.test(s)) return true;
      removed.push(s.trim());
      return false;
    });
    const rest = kept.join("").trim();
    // 行がまるごと消えた時は行ごと落とす（空行を残さない）
    if (rest) outLines.push(rest);
  }
  // ★ 2026-09-20 全件監査で見つけたバグ: 1文字も落としていない時に空行の畳み込み・trim をしてしまい、
  //   実送信12,046通のうち**136通が「落とした物ゼロなのに変わる」**状態だった（本文の勝手な整形）。
  //   落とす物が無ければ**元のテキストをそのまま返す**。
  if (removed.length === 0) return { text, removed: [] };
  // 落とした時だけ、残った空行を畳む（「はい！！\n\n（落とした行）\n\n本文」が空行3つにならないように）
  const out = outLines.join("\n").replace(/\n{3,}/g, "\n\n").trim();
  // 落とした結果ほとんど残らない時は、元のまま返す（本文を空にしない）
  if (out.length < MIN_REMAIN) return { text, removed: [] };
  return { text: out, removed };
}

/** 検査用（final-check・監査スクリプトが同じ判定を使う＝四者同名） */
export function hasApplyReceivedClaim(text: string | null | undefined): boolean {
  return APPLY_RECEIVED_RE.test(text ?? "");
}

// ─── 申込フォーマットの流れ（ここから先は「正しい場面」を見分けるための道具）───────────────
//   竹内「申込情報がどういう場面でおくられてるか流れ分かれば理解できる」
//   ①スタッフが申込フォーマットを送る（AIX【申込へ】または手打ち・実送信150通）
//   ②お客様が記入して返す（【お申込者様記入欄】＋項目）
//   ③スタッフは「ご入力いただきありがとうございます」「お送り頂きありがとうございます」で受ける

/** ①申込フォーマットの送付（実送信150通の定型） */
export const APPLY_FORMAT_SENT_RE =
  /お申込(?:み)?に必要な(?:ご)?情報となります|【お申込者様記入欄】|上記フォーマット(?:に)?ご?入力/;

/** ②お客様が記入して返した申込フォーマット */
export const APPLY_FORM_FILLED_RE =
  /【お申込者様記入欄】|(?:・|①)[^\n]{0,8}(?:入居希望日|氏名|フリガナ|生年月日)/;

/** ③記入が届いた時にスタッフが実際に使う受け方（実データ。ここに「受け取りました」は無い） */
export const APPLY_FORM_ACK_LITERAL = "ご入力いただきありがとうございます😊！！";
