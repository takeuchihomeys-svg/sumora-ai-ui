// お客様が送った複数の物件の募集状況を確かめる宣言の言い回しを、スタッフの実送信の形にそろえる出口（純関数）。
//
// 2026-10-02 竹内さん（YUMA の LINE「お送り頂きました7件の物件の募集状況を、本日管理会社の営業開始後に一括確認させて頂きます！！
//   空きがございましたら、最大限割引させて頂いた初期費用の御見積書とあわせてご連絡させて頂きます！！」を読んで）:
//   「全て確認させて頂きます！！」が実際の言い方。「空きがございましたら」ではなく前向きに「募集されているお部屋の…」
//   （例「募集されているお部屋の最大限割引した初期費用の御見積書とあわせてご連絡させて頂きます」）。
// 線（scripts/audit-bulk-check-wording.ts・365日の人の手打ち 6,029通）:
//   「一括…確認」0通・「空き（が）ございましたら／ありましたら／あれば」0通 ↔ 「全て（の）…確認させて頂きます」11通（9/12「お送り頂きました7件全ての
//   募集状況確認させて頂きます😊！！確認出来次第、最大限割引しました初期費用の御見積書とあわせてご連絡させて頂きます！！」）。
//   出所: 「一括確認」はナレッジ（ai_reply_knowledge）5行の文（「受領宣言＋一括確認の約束」等）。入口は line-reply-prompts のパターンC と、そのナレッジの文の言い換え。
//   この出口は人の手打ちで変わる 0通（同スクリプト）＝誤って変える事が無い形だけ。

export type WordingFix = { text: string; changes: string[] };

/** 「一括確認させて頂きます」「一括で確認させて頂きます」「一括して確認」→「全て確認させて頂きます」 */
const BULK_RE = /一括(?:で|して)?(?=確認させて(?:頂|いただ)きます)/g;
/** 「空きがございましたら、最大限割引…御見積書とあわせて」→「募集されているお部屋の最大限割引…」（後ろが見積書の約束の時だけ） */
const VACANCY_IF_RE = /(?:お部屋に)?(?:空き|空室)(?:が|の)?(?:ございましたら|御座いましたら|ありましたら|あれば|ある場合は?)[、,]?\s*(?=最大限割引)/g;

export function fixBulkCheckWording(text: string | null | undefined): WordingFix {
  let s = String(text ?? "");
  const changes: string[] = [];
  s = s.replace(BULK_RE, (m) => { changes.push(`${m}確認→全て確認`); return "全て"; });
  s = s.replace(VACANCY_IF_RE, (m) => { changes.push(`${m.trim()}→募集されているお部屋の`); return "募集されているお部屋の"; });
  return { text: s, changes };
}
