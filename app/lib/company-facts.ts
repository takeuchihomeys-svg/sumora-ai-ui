/**
 * 初期費用の支払い方法（分割・カード払い・一括・振込のみか）を聞いている1通か（純関数）。
 * 2026-09-30 みこと「初期費用分割は難しいですよね🥲」の当たり漏れで作った。線は実データ（365日・お客様の発言）を全部読んで引いた
 * （scripts/audit-payment-method-question.ts）。保証会社の審査の話（リボ・限度額・滞納・ブラック）は呼び出し側の not で外す。
 */
export function isPaymentMethodQuestion(t: string): boolean {
  const s = t ?? "";
  // ① クレジットカード払いの可否（旧 ask と同じ形＋デビット）
  if (/(?:クレジット|クレカ|デビット)(?:カード)?[^。\n]{0,10}(?:払|決済|支払|でき|出来|可能|大丈夫|使え|いけ)/.test(s)) return true;
  if (/(?<!在留|キャッシュ|マイナンバー|ポイント|交通系)カード(?:払い|決済|で(?:の)?(?:お?支払|払)|支払)/.test(s)) return true;
  // ② 分割: 可否・希望・「難しいですよね」「無理ですよね」の確かめ・「分割とか」・「初期費用（の）分割」
  //   ⚠ 「分割して送ります」等の送り方の話は外す
  if (/分割/.test(s) && !/分割(?:して|で)?(?:送|お送)/.test(s)) {
    // 窓は20字（07-07 条件フォーム「初期費用の分割や家賃に組み込んでお支払いは可能でしょうか？」の可能は分割から16字）
    if (/分割(?:払い|でのお?支払い?|のお?支払い?)?[^。\n]{0,20}(?:でき|出来|可能|大丈夫|ですか|ますか|いけ|難し|厳し|無理|だめ|ダメ|不可|ないですよね|ですよね|とか|希望|したい|にして|したく|頂け|いただけ|お願い|どんな|使え|何回)/.test(s)) return true;
    // 「初期費 用の分割」（改行・空白で割れる）・条件フォームの「10万まで（分割可）」も
    if (/初期費\s?用(?:の|を|は|も)?分割|分割(?:可|OK|ok|希望)|分割(?:払い)?(?:が|の)?(?:出来る|できる)(?:ところ|所|物件)/.test(s)) return true;
    if (/^\s*分割(?:払い)?(?:とか|って|は)?[？?]?\s*$/.test(s)) return true;
  }
  // ③ 一括でないとだめか（「クレジットがない場合は一括ですよね？」「一括しかできない？」）
  if (/一括(?:払い)?[^。\n]{0,10}(?:しか|のみ|だけ|じゃないと|でないと|ですよね|ですか|でしょうか|になり|必須|無理|難し)/.test(s)) return true;
  // ④ 初期費用の支払い方法・振込のみか
  if (/(?:振込|振り込み|お振込|お振り込み)(?:み)?(?:のみ|だけ|しか)/.test(s)) return true;
  if (/初期費用[^。\n]{0,10}(?:支払い?方法|お?支払方法|払い方)|(?:支払い?方法|お?支払方法|払い方)[^。\n]{0,10}初期費用/.test(s)) return true;
  return false;
}

/**
 * 初期費用を「いつ」払うかの質問か（純関数）。
 * 2026-10-01 YUMA の再生（本番の会話 ab7ea742 9/25「初期費用の支払いはいつですか？」）: 支払い方法の拾い（isPaymentMethodQuestion）に「いつ」が無く、
 *   事実が届かず DeepSeek の下書きが「管理会社の規定により異なるため、確認させて頂きます」になった（スタッフは「ご入居日から5日から1週間ほど前」と即答・穴:G1）。
 *   線は scripts/audit-payment-timing.ts（365日・お客様の発言を全部読んだ）。
 */
export function isPaymentTimingQuestion(t: string): boolean {
  const s = t ?? "";
  if (/(?:支払|払い|払う|振込|振り込|入金)[^。\n]{0,10}(?:いつ|タイミング|時期|何日前|いつまで)/.test(s)) return true;
  if (/(?:いつ|どのタイミング|何日前)[^。\n]{0,10}(?:支払|払|振込|振り込|入金)/.test(s)) return true;
  if (/前払い(?:です|でしょう|ですよね)/.test(s)) return true;
  return false;
}

