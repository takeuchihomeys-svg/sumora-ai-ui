/** 通の区切り（reply-context.MSG_SEP と同じ。依存ゼロを保つためここで持つ） */
const UNIT_SEP_RE = /\n⁣\n/;
/**
 * 画像の書き起こし（[画像] で始まる通）は当てない。
 * 2026-09-23 S6 の実測（今月の当たり76通を全部読んだ）: 当たりの50%（38通）が TikTok／SUUMO の画面文字
 *   （「初期費用ゼロ（前家賃だけ）」→日割／「取り扱い店舗」→店舗／「室内写真」→写真）で、お客様は何も聞いていないのに
 *   「お客様はこれを質問している。先に本文で必ず答える」が必ず含める内容に足されていた。
 *   実物で店舗・写真を聞いた発言に画像は0通なので誤削除0。brain-core は直近3通を結合して渡すので、1通ずつ（配列）で判定する。
 */
const IMAGE_UNIT_RE = /^\s*\[(?:画像|動画|スタンプ|ファイル)\]/;

function unitsOf(customerText: string | string[] | null | undefined): string[] {
  const arr = Array.isArray(customerText) ? customerText : [(customerText ?? "")];
  return arr
    .flatMap((t) => (t ?? "").split(UNIT_SEP_RE))
    .map((u) => u.trim())
    .filter((u) => u && !IMAGE_UNIT_RE.test(u));
}

/** お客様の発言に当たる事実だけを返す（当たらなければ空）。配列なら1通ずつ判定（画像の通は外す） */
export function matchCompanyFacts(customerText: string | string[] | null | undefined): CompanyFact[] {
  const units = unitsOf(customerText);
  if (units.length === 0) return [];
  const asked = (f: CompanyFact, t: string) => (typeof f.ask === "function" ? f.ask(t) : f.ask.test(t));
  return COMPANY_FACTS.filter((f) => units.some((t) => asked(f, t) && !(f.not && f.not.test(t))));
}

/**
 * プロンプトに入れる1ブロック。当たらなければ空文字（関係ない会話には一切出さない）。
 * ⚠ 送る文ではなく事実として渡し、「反することを書かない」だけを求める（丸写しを促さない）。
 */
export function buildCompanyFactsNote(customerText: string | string[] | null | undefined): string {
  const hit = matchCompanyFacts(customerText);
  if (hit.length === 0) return "";
  const lines = hit.map((f) => `- ${f.fact}`);
  return `\n【🏢 会社として答えが決まっている事実（お客様が今これを聞いている）】\n${lines.join("\n")}\n`
    // 2026-09-23 生成プロンプトを書き出して分かった穴: お客様の発言が「承知いたしました」等で始まると
    //   場面が【検討中フォロー】と読まれ、必ず含める内容が「急かさない受け止め＋ピックアップ宣言」になり、
    //   事実はプロンプトに入っているのに質問に答えない（しかも『ご来店の際に…』と店舗訪問を受け入れた）。
    //   実データでは 2.0%（120日で48件）と少ないが、自動返信では事故になるので1行で優先を宣言する。
    //   ⚠ 「受け止め」と「質問に答える」は両立するので、他の必須要素と衝突しない（打ち消し合わない）。
    + `→ **お客様はこれを質問している。受け止めや次の提案より先に、この質問へ本文で必ず答える**（他の必須要素と両立させる）。\n`
    + `→ この事実に反することを書かない。分からない事を推測で断定しない（物件・保証会社によって変わる事は「確認します」と答える）。\n`
    + `→ ここに無い事（保証会社の名前や種類・家賃や初期費用の額・入居可能日・募集状況・設備の有無）は**物件によって変わる**ので、事実として言い切らない。\n`;
}
