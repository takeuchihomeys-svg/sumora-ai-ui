// app/lib/condition-expansion.ts
// 条件の「追加・許容」を「変更」と区別する（純関数・DB 依存なし）。
//
// 2026-09-19 竹内（タマキ事例）「その周辺でも大丈夫ですと伝えられているので、限定したら文がおかしくなる。
//   そもそも前に条件を送ってくれていたうえで、この周辺も大丈夫という事なので、その周辺も併せて探す旨から
//   大丈夫だが、限定しない」:
//   お客様「職場が 1人は淀川区（柴島とか新大阪、三国、）と1人は天六あたりなので **その周辺でも大丈夫です**」
//   AI下書き「**淀川区（柴島・新大阪・三国）、天六周辺エリアから**タマキさんにオススメできるお部屋ピックアップ…」
//   実送信「タマキさん達にオススメできるお部屋ピックアップさせて頂きます！！」（エリアを限定していない）
//
// 何が起きていたか:
//   generate-reply の conditionChangeNote（condition_relax 分岐）が
//   「かしこまりました！！**[変更後の条件を具体的に反映]で**…」と指示しており、
//   「でも大丈夫」で**足された**エリアを「変更後の条件」として復唱させていた。
//   追加を変更として書くと、**前に送ってもらった条件が置き換わって消える**。
//
// 実データ（365日・お客様の「〜でも大丈夫／〜も大丈夫／〜まで広げて／〜でも探して」＋エリア語 36件）:
//   既に条件がある場面（継続）28件のうち、スタッフが「〇〇周辺全域から」と**限定した**のは **4件（14%）**。
//   残り86%は限定していない。スタッフの型は
//     「玉造付近**まで含め**、初期費用を抑えられ…」
//     「服部天神・曽根・豊中市・武庫之荘周辺エリア**も含めて**しょうじさんのご希望のご条件にあったお部屋を…」
//     「伏見駅・竹田駅周辺**も含めて**うのさんのご条件に合ったお部屋…」
//     「タマキさん達にオススメできるお部屋ピックアップ…」（エリアに触れない）
//   ＝ **足す言い方（〜も含めて）＋「（既存の）ご条件に合ったお部屋」** が正しい型。
//
// 設計知見「決定論で算出できる値は LLM に選ばせない」に沿って、
// 「追加・許容か」はブレインの condition_change_type ではなくこの純関数で決める
// （ブレインは area_change / condition_relax のどちらにも倒れうる）。

/** 追加・許容の言い方（「〜でも大丈夫」「〜も可能」「〜まで広げて」「〜も探して」） */
// 2026-09-19 実データで漏れた形を足した:「最悪どこ**でもいい**っす」（裸の「いい」）・「どこら辺**でも**大丈夫」
// 2026-09-19 監査で締めた: 裸の「も探し」は「現在**も探し**ております」（こちらが探している報告）に当たったので依頼形だけにする
const EXPANSION_RE =
  /(?:でも)\s*(?:大丈夫|いい|良い|よい|okです|ok|オッケー|構いま|かまいま|平気|可能|検討|探し|見て|見たい)|(?:^|[^で])も\s*(?:大丈夫|いい|良い|よい|構いま|かまいま|平気|可能|含め|入れ|視野|候補)|も\s*探して\s*(?:ほし|欲し|下さ|ください|もら|頂|いただ)|まで\s*広げ|まで\s*(?:含め|見て|探し)|広げ(?:て|ても)\s*(?:探|いい|良|大丈夫)/i;

/**
 * 追加・許容の判定に使ってよい文脈。
 * 2026-09-19 実データ9,026件に当てた監査で、単漢字の「市」「町」「駐車場」で誤爆していた:
 *   「新しく**市**に確定申告し、コピーを写真提出でも大丈夫でしょうか？」（書類の話）
 *   「2台目の**駐車場**の契約って可能ですか？」（契約の話）
 * → エリアは**接尾辞つきの語**（〇〇駅・〇〇区・〇〇線…）でだけ認める。
 */
//   曖昧な接尾辞（区・市・町・村・線）は**前に地名が要る**。単独で地名を表す語（駅・エリア・周辺…）はそのまま認める
//   （「**駅**はどこら辺でも大丈夫です」「その**周辺**でも大丈夫です」のように地名が前に無い言い方が実データにある）
const AREA_TOKEN_RE =
  /[一-龥ぁ-んァ-ヶーa-zA-Z0-9]{1,8}(?:駅|区|市内|市|町|村|沿線|線)|駅|沿線|エリア|方面|周辺|あたり|辺り|付近/;
/** エリア以外で「条件の追加」になりうる語（家賃・間取り・設備） */
const SPEC_TOKEN_RE = /家賃|賃料|間取り|築年|徒歩|広さ|ペット|1[KLRD]|2[KLD]|3[KLD]|[０-９0-9]+(?:万|円)/;

/**
 * 条件の話ではない文脈（書類・手続き・契約・支払い）。ここでの「〜でも大丈夫」は条件の追加ではない。
 * 2026-09-19 監査で拾ってしまっていた実物から作った。
 */
const NOT_CONDITION_CTX_RE =
  /書類|提出|確定申告|謄本|保険証|身分証|免許証|マイナンバー|鍵|引き渡し|引渡|振込|支払|入金|審査|名義|保証人|緊急連絡先|印鑑|写真で|コピー/;
/** 既にやり取りしている物件への言及（route.ts の EXISTING_PROPERTY_REF_RE と同じ考え方） */
const EXISTING_REF_RE =
  /送って(?:もらった|いただいた|くださった|頂いた)|先日の|先程の|さっきの|この(?:物件|お?部屋)|その(?:物件|お?部屋)|こちらの(?:物件|お?部屋)|[0-9０-９]+(?:件目|つ目|番目)|[0-9０-９]{1,2}階の(?:お?部屋|物件)/;

/**
 * 「時期」だけの許容は条件の追加ではない（「入居はいつでも大丈夫です」）。
 * これを追加として扱うと、エリアの話でもないのに「も含めて」の型に倒れる。
 */
const TIME_ONLY_RE = /(?:いつ|何時|時期|入居日?|引っ越し|引越し)\s*(?:で?も)\s*(?:大丈夫|いい|良い|可能|構いま)/;

/** 行き先が限定されない曖昧な許容（「どこでも」「最悪どこでも」）＝エリア名を書かせない */
// 「どこ**ら辺**でも大丈夫」のように間に語が挟まるので、句読点をまたがない範囲で少しだけ許す
const VAGUE_ANYWHERE_RE = /(?:どこ|何処|どちら|どの駅|どのエリア)[^。、\n]{0,4}(?:で?も)\s*(?:大丈夫|いい|良い|よい|可能|構いま|かまいま|オッケー|ok)/i;

export type ConditionExpansion = {
  /** 追加・許容の言い方か（true なら「変更」ではなく「足す」） */
  expanded: boolean;
  /** 行き先が曖昧（どこでもいい）＝エリア名を復唱させない */
  vague: boolean;
  reason: string;
};

/**
 * お客様の発言が「条件の追加・許容」かを決める。
 * 追加なら、返信は「〇〇も含めて（既存の）ご条件に合ったお部屋」＝**今までの条件を消さない**。
 */
export function detectConditionExpansion(text: string | null | undefined): ConditionExpansion {
  const msg = (text ?? "").normalize("NFKC").trim().slice(0, 800);
  const no = (reason: string): ConditionExpansion => ({ expanded: false, vague: false, reason });
  if (!msg) return no("empty");
  if (!EXPANSION_RE.test(msg)) return no("no_expansion_phrase");
  if (NOT_CONDITION_CTX_RE.test(msg)) return no("not_condition_ctx");
  if (EXISTING_REF_RE.test(msg)) return no("existing_property_ref");
  // 「いつでも大丈夫」だけ（他に許容の言い方が無い）なら時期の話＝追加ではない
  const withoutTime = msg.replace(new RegExp(TIME_ONLY_RE.source, "g"), "");
  if (!EXPANSION_RE.test(withoutTime)) return no("time_only");
  // 許容の言い方と同じ文にエリア・条件の語があること（文をまたぐと別の話になる）
  // 2026-09-19 監査: 内覧の集合場所（「大国町の方から見ても大丈夫ですか？」）が当たっていたので、その文は使わない
  const VIEWING_SENT_RE = /内覧|内見|見学|待ち合わせ|待合せ|集合|現地/;
  const sentences = withoutTime.split(/[。．\n！!？?]/).filter((s) => s.trim());
  const usable = (s: string) => EXPANSION_RE.test(s) && !VIEWING_SENT_RE.test(s);
  const nearby = sentences.some((s) => usable(s) && (AREA_TOKEN_RE.test(s) || SPEC_TOKEN_RE.test(s)));
  // 同じ文に無くても、直前の文にエリアがあれば拾う（タマキ「…天六あたりなので／その周辺でも大丈夫です」）
  const prevHasArea = sentences.some((s, i) => usable(s) && i > 0 && AREA_TOKEN_RE.test(sentences[i - 1]));
  if (!nearby && !prevHasArea) return no("no_condition_near");
  const vague = VAGUE_ANYWHERE_RE.test(msg);
  return { expanded: true, vague, reason: vague ? "expanded_vague" : "expanded" };
}

/**
 * 追加の場面で使う返信の型（材料としてそのまま渡す）。
 * 実送信の言い方（「〜も含めて」「〜まで含め」）だけを骨組みにする。
 */
export function buildExpansionNote(v: ConditionExpansion, customerName: string): string {
  if (!v.expanded) return "";
  const name = customerName.trim() || "お客様";
  const areaLine = v.vague
    ? "・行き先を「どこでも」と言われているので、**エリア名は書かない**（「" + name + "にオススメできるお部屋」で受ける）"
    : "・足されたエリア・条件は「〇〇**も含めて**」の形で書く（「〇〇周辺全域から」「〇〇エリアから」と**限定する形は禁止**）";
  return `\n【➕ 条件の追加・許容（限定しない・最優先）】お客様は「〜でも大丈夫」と**今までの条件に足して**言っている。変更ではない。
${areaLine}
・**今までの条件・エリアを打ち消さない**（前に頂いたご条件は引き続き探す。今回の発言のエリアだけに絞った書き方をしない）
・正しい型:「かしこまりました！！／〇〇も含めて${name}のご希望のご条件に合ったお部屋をピックアップしてお送りさせて頂きます！！」
・実送信の言い方はこの2つだけ:「〇〇も含めて」「〇〇まで含め」（365日の実データ。「〇〇周辺全域から」で限定したのは14%）`;
}

// ── 【やらない判断】出口の決定論（「〇〇周辺全域から」→「〇〇も含めて」の自動置換）は入れない ──
//
// 2026-09-19 一度作って、設計知見「落とす仕組みを入れたら過去の下書き全部に当てて目で読む」に従い
// 過去の AI 下書き1,000件に当てたところ、**書き換わった92件が全部改悪**だった。実物:
//   旧「杉本町周辺全域から築年数が新しめの1LDK・2LDKのお部屋で chibi さんにオススメできる…」
//   新「杉本町も含めて築年数が新しめの…」          ← 既存条件のエリアなので限定が正しい。改悪
//   旧「🌟大国町・本町・堺筋本町エリアより新着物件」
//   新「🌟大国町・本町・堺筋本町も含めて新着物件」  ← 文が壊れる
//
// 理由: 本文に出てくるエリア名から「今回足されたエリア」と「元からの条件のエリア」を**区別できない**。
//   区別するには会話側の材料が要るが、その材料（お客様の発言のどのエリアが新しいか）は
//   AIX の物件送付文など別経路では手に入らない。
// → **材料（buildExpansionNote）だけで直す**。指示が落ちるなら、出口ではなく
//   「その場面の下書きが実際どうなったか」を測って次の手を決める（改悪の方が気付きにくいため）。
//
// 設計知見「落とす仕組みは『落としすぎ』も『落とし漏れ』も事故になるが、落としすぎの方が気付きにくい」
