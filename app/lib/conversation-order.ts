// app/lib/conversation-order.ts
// 一覧（LINE の会話リスト）の並び順。純関数・DB 依存なし。
//
// ── 2026-09-18 の経過（同じ日に3回変えた。順番を残す）──────────────────────────
//   ① 竹内「必ずのお客さんはLINEの上に上がるようにする。忘れないようにする為」
//      → 【必ず】（お客様への約束・未履行）を一覧全体の先頭・約束が古い順にした
//   ② 竹内「メッセージがきているお客さんで時間最近の方が上に配置。この必ずは、
//          メッセージが来ていない中ならメッセージ来ていない中で上、来ているなら来ている中で上」
//      → 返事待ちを第一キーにし、【必ず】はその組の中で上げた
//   ③ 竹内「**LINE時間系列バラバラになっているので、読みにくい。本来のLINEのように時間最新順に戻す**」
//      → 並べ替えをやめ、直近やり取り順だけに戻した（今ここ）
//
// ③ の理由: 組分け（返事待ち／【必ず】）を入れると、画面では時刻が
//   19:37 → 17:37 → 20:19 → 18:08 のように行ったり来たりして読めなくなる。
//   一覧は「上から順に新しい」という当たり前の読み方そのものが情報で、
//   並べ替えて得られる「忘れない」より、その読みやすさの方が毎日効く。
//   【必ず】は 🔴必ず バッジ・会話画面の赤帯・カレンダー・翌朝の日報の4か所で届いているので、
//   並びまで変えなくても消えない（設計知見「届く場所を複数持つ」）。

/** 並べる時に見る1件分 */
export type ConversationOrderKey = {
  /** 直近やり取りの時刻（ms） */
  updatedAtMs: number;
};

/** 時刻の文字列を ms に（読めない時は 0＝一番下）。並びに NaN を混ぜない */
export function sortMsOf(iso: string | null | undefined): number {
  const t = Date.parse(iso ?? "");
  return Number.isFinite(t) ? t : 0;
}

/**
 * 一覧の並び。直近やり取り順（新しい方が上）だけ。
 * ここに「〜の時は上に出す」を足す時は、画面で時刻が前後することを竹内さんに見せてから決める。
 */
export function compareConversationOrder(a: ConversationOrderKey, b: ConversationOrderKey): number {
  return b.updatedAtMs - a.updatedAtMs;
}
