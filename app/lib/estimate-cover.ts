// app/lib/estimate-cover.ts
// 見積書に添えるカバーレター（2通目）から「金額文のブロック」を落とす（純関数・DB 依存なし）。
//
// 2026-09-20 竹内（H さん事例）の検証中に見つけた2つ目の崩れ:
//   AIX【見積書送る】をハイツカトレア B 202号室（スモ割0円）で通したら、2通目に
//     **【プレサンス阿倍野松崎805号室】**
//     初期費用さらに
//     🌟68,000円割引させて頂き
//     初期費用：152,000円
//     ※ご入居日によって日割家賃が発生致します。
//   が入った。**今回の物件でも今回の金額でもない**（手本として渡した他のお客様の文を写している）。
//   お客様に別の物件の初期費用を送る形なので、慶次事例（他のお客様の条件の混入）より危ない。
//
// 【なぜ既存の出口で落ちなかったか】route.ts に後処理はあったが、落としていたのは
//   「一般的な不動産業者」「節約＋円」を含む行**だけ**。だから節約行は消え、
//   物件名・「初期費用さらに」・割引・初期費用・日割注記はそのまま残っていた。
//
// 【実データで線を引いた】実送信365日 11,990通のうち「御見積書・お見積書」を含む 838通、
//   そのうち金額文の見出しで始まらない（＝カバーレター）835通:
//     金額（初期費用：〇円／🌟〇円割引させて頂き／一般的な不動産業者より）を含む … **5通（1%）**
//     【物件名】を含む                                                   … **6通（1%）**
//   金額を含む5通を全部読むと、3通は**1通目の金額文が同じメッセージに連結されているだけ**
//   （Noriyuki さん・KTIレジデンス）、残り2通は文の中で数えている形:
//     「初期費用74,250円・ギガ賃貸なら一般的な不動産業者より65,600円節約出来ますので、…」
//     「こちら最終の…御見積書となり合計で139,000円割引させて頂きます！！」
//   ＝ **行まるごとが金額文の形をしている時だけ落とす**（文の中で数えている形は残す）。
//     実送信835通に当てて誤削除0になる線を採った（scripts/audit-estimate-cover.ts）。

/**
 * 【物件名 202号室】だけの行。
 * ⚠ **単独では落とさない**。実送信835通に当てたら2通で本物の文を消していた:
 *   「【エスティメゾン南堀江 1103号室】／最大限割引した初期費用のお見積書作成しお送りさせて頂きます」
 *     ＝スタッフが物件名を見出しにして書いた本物の文
 *   「④【希望築年数】」＝条件ヒアリングフォームの項目（⑦【初期費用の限度額】も同じ形）
 * → **直後（空行を除く次の行）が金額行の時だけ**落とす（金額ブロックの見出しの時だけ）。
 */
const BRACKET_HEAD_RE = /^\s*(?:[①-⑨]|[0-9]{1,2}[.．])?\s*【[^】]{1,40}】\s*$/;

/**
 * 金額の並び。実際の数字だけでなく**〇でマスクされた形**も見る。
 * 2026-09-20 本番で「🌟〇〇〇,〇〇〇円割引させて頂き／初期費用：〇〇〇,〇〇〇円」が出た
 * （手本の金額を伏せた形をそのまま写していた）。〇のままお客様に送っても意味が無い。
 */
const NUM = "[0-9０-９〇○◯×✕＊*,，]+";
/** 行頭の箇条書き・番号（「・初期費用さらに🌟36,000円割引させて頂き」の形が本番で出た） */
const BULLET = "(?:[・･\\-−*＊]|[0-9０-９]{1,2}[.．)）])?\\s*";

/** 落とす行の形。どれも「行まるごとが金額文の一部」の時だけ当たる */
const AMOUNT_BLOCK_LINE_RES: RegExp[] = [
  // 「初期費用さらに」だけの行／箇条書き／同じ行に割引が続く形（本番で出た「・初期費用さらに🌟36,000円割引させて頂き」）
  new RegExp(`^\\s*${BULLET}初期費用さらに\\s*(?:(?:🌟|⭐|★|☆)?\\s*${NUM}\\s*円\\s*割引させて(?:頂|いただ)き)?\\s*$`, "u"),
  // 🌟24,000円割引させて頂き（🌟が必須＝「合計で139,000円割引させて頂きます！！」は残る）
  // ※ 🌟 は2コード単位なので文字クラス [🌟⭐] に入れると割れて当たらない（テストで捕まえた）。並べて書く
  new RegExp(`^\\s*${BULLET}(?:🌟|⭐|★|☆)\\s*${NUM}\\s*円\\s*割引させて(?:頂|いただ)き\\s*$`, "u"),
  // 初期費用：199,500円（コロン必須＝「初期費用74,250円・…」は残る）
  new RegExp(`^\\s*${BULLET}初期費用\\s*[：:]\\s*${NUM}\\s*円\\s*$`),
  // スモラなら一般的な不動産業者より97,700円節約出来ます！！（行末が！！＝「節約出来ますので、…」は残る）
  new RegExp(`^\\s*${BULLET}\\S{1,10}なら一般的な不動産業者より\\s*${NUM}\\s*円\\s*節約出来ま[すし][。！!]*\\s*$`),
];

/**
 * ※ご入居日によって日割家賃が発生致します。（1通目に必ず入るので2通目では重複）
 * ⚠ これも**単独では落とさない**。実送信で物件オススメの文（SOAR SHINIMAMIYA 703・2026-08-22）の
 *   末尾にこの注記だけが付いている通があり、落とすと本物の情報が消える。
 * → **同じ文の中に金額行がある時だけ**落とす。
 */
const DAY_RENT_NOTE_RE = /^\s*※\s*ご?入居日によって日割(?:り)?家賃が(?:発生致します|変動します)[。．]?\s*$/;

const norm = (line: string) => (line ?? "").replace(/\*\*/g, "").trim();   // Haiku が ** で囲むことがある

export function isEstimateAmountLine(line: string): boolean {
  const l = norm(line);
  if (!l) return false;
  return AMOUNT_BLOCK_LINE_RES.some((re) => re.test(l));
}

/** 【物件名】の行が「金額ブロックの見出し」か（直後の非空行が金額行なら見出し） */
export function isAmountBlockHeading(lines: ReadonlyArray<string>, i: number): boolean {
  if (!BRACKET_HEAD_RE.test(norm(lines[i] ?? ""))) return false;
  for (let j = i + 1; j < lines.length; j++) {
    if (!norm(lines[j])) continue;            // 空行は飛ばす
    return isEstimateAmountLine(lines[j]);    // 最初に出てくる中身が金額行なら見出し
  }
  return false;
}

/**
 * カバーレターから金額文のブロックを落とす。
 * 行単位でしか落とさない（文の中で金額に触れている形は実送信にあるので残す）。
 */
/**
 * 「○○さん」のままお客様に送らない（2026-09-20 本番検証で出た）。
 *
 * 【出所】ai_reply_knowledge の principle に、手本がプレースホルダのまま入っている:
 *   「○○さんお気に召されましたらお部屋ご都合よろしいお日にちにお部屋ご案内させて頂きます😊」
 *   「案内文中の『○○さん』はお客様の名前を指すプレースホルダーである。実際の顧客名に置き換えて…」
 *   ＝ ナレッジ自身が「○○を残すな」と書いているのに、AI はそのまま写すことがある。
 * 【線】スタッフの実送信365日で「○○さん」は **0件**。残っていたら必ず誤り。
 * 【直し方】落とすのではなく**置き換える**（落とすと文が壊れる）。
 *   名前が分かっていれば名前に、分からなければ呼びかけごと外す。
 * ※「○月○日（曜日）○○:○○」のような時刻のプレースホルダには当てない（さん・様が続く時だけ）。
 */
//   2026-09-20 本番で【お客様名】という形も出た（「【お客様名】さんお世話になっております！！」）。
//   見出しではなく**名前のプレースホルダ**なので、外すのではなく名前に置き換える
//   （外すと「さんお世話になっております」と壊れる）。
const NAME_PLACEHOLDER_RE = /(?:[○〇◯]{2,}|【(?:お客様名|顧客名|お名前|customer_?name)】)\s*(さん|様)/g;

export function fixNamePlaceholder(text: string, customerName?: string | null): { text: string; fixed: number } {
  if (!text) return { text, fixed: 0 };
  let fixed = 0;
  // ⚠ 渡ってくる名前は既に敬称付き（route.ts は `${familyName}さん` か「お客様」を渡す）。
  //   2026-09-20 本番で「YUMAさん**さん**」「YUMAさん**様**」と二重になった（最初の実装の誤り）。
  //   敬称を一度外してから、手本側の敬称（さん／様）を付け直す。
  const raw = (customerName ?? "").trim();
  const isGeneric = /^お客様$/.test(raw);           // 「お客様」はそれ自体が呼びかけ＝重ねない
  const base = raw.replace(/\s*(さん|様|さま)\s*$/, "");
  const out = text.replace(NAME_PLACEHOLDER_RE, (_m, honorific: string) => {
    fixed++;
    if (isGeneric) return "お客様";
    return base ? `${base}${honorific}` : "";
  });
  return { text: fixed ? out.replace(/ {2,}/g, " ") : text, fixed };
}

// ─── 2026-09-20 竹内「色んなパターンでバグや変な言い回しになっていないか確認」──────────
// 本番14パターンで【見積書送る】を通して2通目に出た実物と、実送信365日 11,998通での件数:
//   「【お客様に送る文】」「【お客様名】さん」「【お客様の現在の状況（状態）】」 … 実送信 **0通**
//   「お世話になっております。ギガ賃貸です。」「スモラでございます😊」        … 実送信 **0通**
//   「こちらのメッセージには返信できません。」                              … 実送信 **0通**
//   「〈」（1文字）                                                      … 1〜3文字の実送信は24通
//                                                                        （中身は「あ」「たあ」＝誤送信）
//   「鈴木さんお世話になっております」（**スタッフ名をお客様の呼称にしている**）… 先頭が「鈴木さん」等は 0通
//     ※「鈴木と申します」「担当の鈴木」など**正当な形は181通**あるので、先頭の呼びかけだけに限る

/**
 * プロンプトの見出し・節名をそのまま写した行。実送信365日 12,016通で **0通**。
 * 2026-09-20 の4回転で出た実物:
 *   【お客様に送る文】／【お客様の現在の状況（状態）】／
 *   【初期費用内訳】記載なし（見積書に金額を書かない）／
 *   【タスク】初期費用の見積書を送付する際の添付メッセージを1つだけ作成してください
 * ⚠ 実送信の【…】は387種類あり、上位は「お申込者様記入欄」79回・「緊急連絡先欄」69回・
 *   「同居人記入欄」44回・条件ヒアリングフォームの項目（「希望築年数」「初期費用の限度額」各19回）。
 *   物件名も【…】に入る。**節名に使われる語だけ**に絞ることで、これらを1つも落とさない。
 */
const PROMPT_HEADING_RE = /^\s*【[^】]{0,24}(?:お客様|タスク|指示|出力|ルール|制約|内訳|前提|参考|注意点|入力)[^】]{0,12}】/;
/** 会社名の名乗り。実送信0通（スモラは「スモラの鈴木と申します」の形でしか出ない） */
const SELF_INTRO_RE = /(?:スモラ|ギガ賃貸|イエヤス)(?:です|でございます)[。．！!]?/g;
/** 先頭の呼びかけに使われた名前 */
const LEAD_HONORIFIC_RE = /^\s*([^\s、。，,！!？?「」【】]{1,12})(さん|様)/;
/** 呼びかけに見えるが名前ではない語（置き換えない） */
const NOT_A_NAME = new Set(["皆", "みな", "みなさ", "奥", "旦那", "親御", "お子", "お客", "担当", "管理会社"]);

/** カバーレターとして送るには短すぎる（実送信の1〜3文字はスタッフの誤送信だけ） */
export const COVER_MIN_LENGTH = 4;

export function stripEstimateAmountBlock(cover: string): { text: string; removed: string[] } {
  if (!cover) return { text: cover, removed: [] };
  const lines = cover.split("\n");
  // 金額行が1つでもある時だけ、日割の注記も重複とみなす
  const hasAmount = lines.some(isEstimateAmountLine);
  const removed: string[] = [];
  const kept = lines.filter((line, i) => {
    const drop = isEstimateAmountLine(line)
      || isAmountBlockHeading(lines, i)
      || (hasAmount && DAY_RENT_NOTE_RE.test(norm(line)));
    if (!drop) return true;
    removed.push(line.trim());
    return false;
  });
  if (removed.length === 0) return { text: cover, removed };
  return { text: kept.join("\n").replace(/\n{3,}/g, "\n\n").trim(), removed };
}

/**
 * 2通目（カバーレター）の出口を1つにまとめる。
 * 落とす／置き換える／空にするの3択で、**どれも実送信365日で誤削除0になる線**で引いている。
 * 返す text が空文字なら「2通目を送らない」（1通目の見積書は正常に送れる）。
 */
export function sanitizeCoverLetter(
  cover: string,
  customerName?: string | null,
): { text: string; removed: string[]; fixed: string[] } {
  const removed: string[] = [];
  const fixed: string[] = [];
  let t = (cover ?? "").trim();
  if (!t) return { text: "", removed, fixed };

  // ① 他のお客様の金額ブロック
  {
    const r = stripEstimateAmountBlock(t);
    if (r.removed.length) { removed.push(...r.removed); t = r.text; }
  }
  // ② 名前のプレースホルダ（○○さん／【お客様名】さん）→ 名前。**見出しを外す前にやる**
  //    （【お客様名】は見出しではなく名前なので、外すと「さんお世話になっております」と壊れる）
  {
    const r = fixNamePlaceholder(t, customerName);
    if (r.fixed > 0) { fixed.push(`名前のプレースホルダ ${r.fixed}件 → ${customerName ?? "（削除）"}`); t = r.text; }
  }
  // ③ プロンプトの見出しをそのまま写した形（【お客様に送る文】など・実送信0通）。
  //    **見出しだけ外して後ろの本文は残す**（「【お客様の現在の状況（状態）】お申込み情報を受け取りました」）
  {
    const kept: string[] = [];
    for (const l of t.split("\n")) {
      const bare = l.replace(/\*\*/g, "");
      const m = bare.match(PROMPT_HEADING_RE);
      if (!m) { kept.push(l); continue; }
      removed.push(m[0].trim());
      const rest = bare.slice(m[0].length).trim();
      if (rest) kept.push(rest);          // 後ろに本文が続くなら残す
    }
    t = kept.join("\n");
  }
  // ④ 会社名の名乗り（実送信0通）。行ごとではなく**その文だけ**落とす
  {
    const before = t;
    t = t.replace(SELF_INTRO_RE, "");
    if (t !== before) removed.push("会社名の名乗り");
  }
  t = t.replace(/\n{3,}/g, "\n\n").replace(/[ \t]{2,}/g, " ").trim();

  // ⑤ 先頭の呼びかけがお客様の名前でない（スタッフ名を書いている・実送信0通）
  //    ⚠ 呼び名が分からない時（route.ts が「お客様」を渡す）は**置き換えない**。
  //       base が「お客」になり、正当な「ゆーたさん」を「お客さん」に書き換えてしまう（テストで捕まえた）。
  {
    const raw = (customerName ?? "").trim();
    const base = raw.replace(/\s*(さん|様|さま)\s*$/, "");
    const known = !!base && !/^お客$/.test(base) && !/^お客様$/.test(raw);
    const m = t.match(LEAD_HONORIFIC_RE);
    if (known && m && !NOT_A_NAME.has(m[1]) && m[1] !== base && m[1] !== raw) {
      fixed.push(`先頭の呼びかけ ${m[1]}${m[2]} → ${base}${m[2]}`);
      t = `${base}${m[2]}${t.slice(m[0].length)}`;
    }
  }
  // ⑥ 短すぎる（壊れた出力）＝送らない
  if (t.trim().length < COVER_MIN_LENGTH) {
    if (t.trim()) removed.push(`短すぎる出力「${t.trim()}」`);
    return { text: "", removed, fixed };
  }
  // ⑦ ★ 受け入れ条件（2026-09-20・3回転目）: **見積書の話をしていない2通目は送らない**
  //   出口に落とす形を足し続けても、AI は形を変えて出し続けた（5回変わった）。
  //   カバーレターは**無くても困らない**（1通目の見積書が本体）ので、
  //   「落とす物を並べる」のをやめて「**通す物を決める**」形にした。
  //   実送信365日のカバーレター相当 859通は**全部「見積」を含む**（落ちるのは0通）。
  //   一方、本番で出た「お申込み情報を確かに受け取りました」「出力は行いません」
  //   「内容をこちらで確認することができない状態でございます」はどれも見積書の話をしていない。
  if (!/見積/.test(t)) {
    removed.push(`見積書の話をしていない2通目「${t.slice(0, 40)}」`);
    return { text: "", removed, fixed };
  }
  return { text: t, removed, fixed };
}
