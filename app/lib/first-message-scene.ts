/**
 * 1通目の書き方（ユーザー文の最後に置く・ここより前の指示と食い違う所はこちらが正）。
 * 指示の言葉に「魅力・強み・特別感・暮らしやすい」等を入れない（指示の語がそのまま本文に出る）。「〜の1文を添えろ」型の強制もしない。
 */
export function buildFirstSceneNote(i: FirstSceneInput): string {
  const nm = i.name.trim().replace(/さん$/, "");
  const san = nm ? `${nm}さん` : "";
  const L: string[] = [];
  L.push("【この1通目の書き方（スタッフが実際に書いた1通目の形。ここより前の指示・実例と食い違う所はこちらが正）】");
  L.push(`場面: ${i.isNew ? "新着で募集に出た1件" : i.compare ? "これまでにお送りしたお部屋の中から1件をオススメ" : "1件のオススメ"}／${i.vacating ? "退去予定のお部屋（まだご内覧頂けない）" : "空室のお部屋"}`);
  L.push("■ 形");
  L.push("・1行目は「🌟建物名 号室」（資料の字のまま）。");
  if (i.isNew) {
    L.push(`・2段落目の最初の文は「${newArrivalOpening(nm)}」（スタッフの新着の1通目の形そのまま）。この文を「〜、${san ? `${san}に` : ""}かなりオススメ出来るお部屋となります！！」の文の代わりに置く（2つ並べない）。`);
  } else {
    L.push(`・2段落目の最初の文は「（資料の事実を1〜2つ）、${san ? `${san}に` : ""}かなりオススメ出来るお部屋となります！！」の1文。`);
    // 2026-10-01 ローカル生成（比較の場面・3回中1回）で1通目が「お送りさせて頂きましたお部屋の中でも、…」で始まり、2通目の書き出しと重なった
    if (i.compare) L.push("・「お送りさせて頂きましたお部屋の中でも」は1通目に書かない（続けて送る2通目の書き出し。1通目は🌟の物件そのものの紹介）。");
  }
  L.push("・その後の本文は1〜2文（多くて3文）。1文に書く事実は1〜2つ（間取りと広さ／家賃管理費込／築年／駅徒歩／設備／敷金礼金なし）。設備を並べる時は1文に3つまで（スタッフの本文の文で4つ以上並べたのは 0/94文）。");
  L.push("・文は資料の事実で結ぶ（「〜の2DKとなります！！」「〜も完備しております！！」「〜ご入居頂けます！！」の形）。資料に無い感想・住み心地の文は足さない。同じ事（敷金礼金なし・インターネット無料 等）を2回書かない。");
  L.push("・文の終わりは全部「！！」。「。」で終わる文を混ぜない（スタッフの1通目 33通で「。」終わり 0）。");
  // 2026-10-01 竹内「締めは2通目だけでも大丈夫・構成として」: 1通目は締めを書かない（締めは続けて送る2通目に1回だけ）
  L.push("・最後は事実の文（退去予定のお部屋は退去予定を伝える一文）で終える。締めの誘導（ご案内・お申込でお部屋を抑える・ご査収ください）は書かない（次の通に置く）。");
  L.push("・絵文字は無しでよい。入れる時は最後の文の「！！」の直前に1個（😊）。本文の途中には置かない。");
  L.push("・長さは「🌟」の行から最後までで 100〜200字（スタッフの1通目の中央値146字・締め込み）。");
  L.push("");
  L.push("■ スタッフが実際に送った1通目（本文そのまま・締めの文だけ除いた。物件名・金額・広さ・日付はその時の物なので今回の文に持ち込まない。今回の事実は資料から）");
  const pool = FIRST_MESSAGE_EXAMPLES.filter((e) => e.isNew === i.isNew && (i.vacating ? true : !e.vacating));
  const picked = i.vacating ? [...pool.filter((e) => e.vacating), ...pool.filter((e) => !e.vacating)].slice(0, 3) : pool.slice(0, 3);
  picked.forEach((e, k) => { L.push(`--- 実物${k + 1} ---`); L.push(removeRecommendClosing(renderFirstExample(e.text, nm)).text); });
  if (!i.isNew) {
    L.push("--- 本文の行の実物（冒頭の文と締めを除いた行・そのまま） ---");
    for (const b of FIRST_BODY_LINES.slice(1, 4)) L.push(renderFirstExample(b, nm));
  }
  return L.join("\n");
}

/** 出口の検査: 手本の物件名が今回の文に入り込んでいないか（入っていればその語）。allowed（資料・スタッフの入力）にある語は数えない */
export function leakedFirstExampleFacts(text: string | null | undefined, allowed: string | null | undefined): string[] {
  const t = String(text ?? ""), ok = String(allowed ?? "");
  const out: string[] = [];
  for (const e of FIRST_MESSAGE_EXAMPLES) for (const f of e.facts) if (f.length >= 3 && t.includes(f) && !ok.includes(f) && !out.includes(f)) out.push(f);
  return out;
}
