const ALL: Record<string, string> = { ...SIMPLIFIED, ...TRADITIONAL };
const RE = new RegExp(`[${Object.keys(ALL).join("")}]`, "gu");

export function japaneseGlyphFixEnabled(env: Record<string, string | undefined> = typeof process !== "undefined" ? process.env : {}): boolean {
  return (env.JAPANESE_GLYPH_FIX ?? "").toLowerCase() !== "off";
}

/** 中国の字形が入っているか（記録・監査用） */
export function hasChineseGlyph(text: string | null | undefined): boolean {
  RE.lastIndex = 0;
  return RE.test(String(text ?? ""));
}

/**
 * 中国の字形を日本の字形に直す。protect＝直さない名前（お客様の名前・物件名）。呼びかけ（〜さん・様・さま・殿）の直前 8字も直さない。
 * 返り値の fixed は直した字（「话→話」の形）
 */
export function fixChineseGlyphs(text: string, opts: { protect?: ReadonlyArray<string | null | undefined>; env?: Record<string, string | undefined> } = {}): { text: string; fixed: string[] } {
  // 2026-10-14 確かめる人: 日本の資料の「1个月」（ヶの略字）は「個月」ではなく「ヶ月」（个→個は「一个」等の中国語の文だけ）
  const raw = String(text ?? "");
  if (!raw || !japaneseGlyphFixEnabled(opts.env)) return { text: raw, fixed: [] };
  const pre: string[] = [];
  const src = raw.replace(/(?<=[0-9０-９一二三四五六七八九十])个(?=月|所)/g, () => { pre.push("个→ヶ"); return "ヶ"; });
  RE.lastIndex = 0;
  if (!RE.test(src)) return { text: src, fixed: pre };
  // 守る範囲（名前・呼びかけの直前）
  const keep = new Array<boolean>(src.length).fill(false);
  for (const p of opts.protect ?? []) {
    const n = String(p ?? "").trim();
    if (n.length < 1) continue;
    let i = src.indexOf(n);
    while (i >= 0) { for (let k = i; k < i + n.length; k++) keep[k] = true; i = src.indexOf(n, i + n.length); }
  }
  for (const m of src.matchAll(/(?:さん|様|さま|殿|くん|ちゃん)/g)) {
    const end = m.index ?? 0;
    for (let k = Math.max(0, end - 8); k < end; k++) keep[k] = true;
  }
  const fixed: string[] = [...pre];
  let out = "";
  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    const to = ALL[ch];
    if (to !== undefined && !keep[i]) { out += to; fixed.push(`${ch}→${to}`); }
    else out += ch;
  }
  return { text: out, fixed };
}
