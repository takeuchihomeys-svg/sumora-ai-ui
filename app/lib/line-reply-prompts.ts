「引き続き全力でサポートさせて頂きます！！」等のサポート継続宣言を使う場合は、必ずお客様名を文の先頭に置く。
正：「タクミさんご満足頂けるお部屋が見つかるまで引き続き全力でサポートさせて頂きます！！」
