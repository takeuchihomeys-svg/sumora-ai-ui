export function buildPhaseProhibitionNote(phaseKey: string, ctx?: { sentPropertiesCount?: number }): string {
  const def = PHASE_PROHIBITIONS[phaseKey as PhaseKey];
  if (!def) return "";
  const bans = ctx ? def.bans.filter((b) => !b.onlyIf || b.onlyIf(ctx)) : def.bans;
  if (!bans.length) return "";
  return `\n【🚫 ${def.label}フェーズの絶対禁止（final-check STATE_REGRESSION / TIMING_VOCAB_MISMATCH で機械検出・block。AIXタイミング判定・実例・サポート宣言の型より上位）】\n${bans
    .map((b) => `・${b.why}${b.allowIfCustomerAsked ? "（お客様が自ら求めた場合のみ可）" : ""}${b.allowNote ? `（${b.allowNote}）` : ""} → ${b.fix}`)
    .join("\n")}`;
}

