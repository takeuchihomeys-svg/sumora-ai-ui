// app/lib/listing-renovation.ts（純関数・DB/LLM なし・画面とサーバーで共用）
// 資料の文字（property_pickups.pdf_text）から「リノベーション済みの部屋か」を読む。
//
// 2026-10-06 竹内「（1LDK以上で一番新しい部屋を推す）これはお客さんによる　ほかにものベーション物件を押している場合もあるから注意」:
//   スタッフの🌟の本文には「フルリノベーション済みで室内綺麗」「水回りリノベーション」が 839通中 62通。築年だけでは新しさを測れない。
//   資料（2,517行）で「リノベ」47行・「リフォーム」85行。ただし半分は部屋の事ではない（実物を読んだ）:
//     ✗ 「エントランスリノベーション工事予定」（共用部・予定）／「リフォーム前」「リフォーム中」「リフォーム後現状有姿」（現況の断り書き）
//     ✗ 「入居可能時期についてはリフォーム状況によって」「リフォーム時に壁材…変わる可能性」「設備等はリフォーム内容によって異なります」
//     ✗ 「プチリノベ実施!洗面所とトイレに棚新設」（棚だけ）
//     ✓ 「◆リノベーション物件」「備考 リノベーション物件」「, リノベーション ,」（こだわりの札）「内装リフォーム済」「令和7年リフォーム済み」「9月リフォーム済」
//   → 部屋そのものが改装済みと言える形だけを true。文字が無ければ null（分からない）・文字があって形が無ければ false。

// 空白はすべて外してから当てる（PDF の文字は「内 装リフォーム済」「リノベ ーション」のように語の中で割れる）
const POSITIVE: RegExp[] = [
  /フルリノベ/,
  /リノベ(?:ーション)?(?:済|物件|実施|工事済|完了|完成済|ルーム|マンション|住戸|のお部屋|部屋|中)/,
  /(?:水回り|水廻り|水まわり|室内|内装|全面|全室|お部屋|専有部)(?:の)?(?:フル)?リノベ/,
  // こだわりの札の一覧（「,リノベーション,」「・リノベーション1403771（ITANDI の番号）」「◆リノベーション」「!リノベーション!」）と
  // ITANDI の「リノベーション:[内装]…」・リノベの銘柄（「Renottaリノベーション【…】」）
  /(?:^|[,、・◆■★☆!?])リノベーション(?:[,、!◆■★☆]|\d|$)/,
  /リノベーション:\[内装\]/,
  /リノベーション【/,
  /(?:内装|室内|全面|全室|水回り|水廻り)(?:の)?(?:リフォーム|改装)(?:済|完了|しました)/,
  /(?:令和|平成|20)\d{1,2}年(?:\d{1,2}月)?(?:に)?(?:フル)?(?:リフォーム|リノベ(?:ーション)?|改装)(?:済|完了|実施)/,
  /\d{1,2}月(?:に)?(?:リフォーム|リノベ(?:ーション)?)済/,
  /内装一新|全面改装済|フルリフォーム済/,
];
// 部屋の事でない言い方（先に消す）。「リノベーション中」「フルリノベ中」は入居の時には改装済み＝残す。「リフォーム中」は現況の断り書きなので消す
const NEGATIVE: RegExp[] = [
  /(?:エントランス|外壁|外装|共用部分?|廊下|屋上|大規模)(?:の)?(?:リノベ(?:ーション)?|リフォーム|改装)[^,、。・◆■★☆]{0,12}/g,
  /リノベーション:\[外装\][^・]{0,30}/g,
  /(?:リノベ(?:ーション)?|リフォーム)(?:工事)?(?:予定|前|状況|時に|内容|後現[状況]|アップ後|を予定)/g,
  /リフォーム中/g,
  /プチリノベ[^。]{0,30}/g,
  /(?:畳|クロス|壁紙)(?:の)?リフォーム済み?/g,
];

/** 部屋がリノベーション（内装の改装）済みか。文字が無ければ null・あって形が無ければ false */
export function renovationOfText(text: string | null | undefined): boolean | null {
  const raw = String(text ?? "");
  if (!raw.trim()) return null;
  // 全角の英数を揃えて空白を外し、部屋の事でない言い方を先に消す
  let s = raw.normalize("NFKC").replace(/\s+/g, "");
  for (const re of NEGATIVE) s = s.replace(re, "|");
  return POSITIVE.some((re) => re.test(s));
}
