// app/lib/opener-ack-push.ts
// 開口語「はい」か「かしこまりました」か — 了承の後の「お願いします」は新しい依頼とは限らない。純関数・DB 依存なし。
//
// 2026-09-17 竹内（Hina 事例）「この場合は**はい**が答えとして正しい。かしこまりましただと違和感でる。
//   ここの曖昧な違いの部分ちゃんと改善する。根本的なところ。他の場合でも かしこまりました等違う場面なのにでてしまう」
//
// Hina 9/17:
//   20:26 こちら「明日、室内の写真と動画撮影しお送りさせていただきます！！」
//   20:29 こちら「内覧会ですがお時間13:00〜13:30の枠のみ確保出来ております！！／
//                お時間厳しい場合、撮影した室内写真と動画お送りさせて頂きます😌！！」
//   20:57 お客様「承知しました！／時間的に厳しそうなので、／**写真またお願いします**🙇🏻‍♀️」
//   → AI 下書き「**かしこまりました！！**／写真と動画準備でき次第お送りさせて頂きます😊！！」
//   → 実送信「**はい！！**／写真と動画撮影でき次第お送りさせて頂きます😊！！」
//
// 原因: この通は classifyCustomerResponse で kind=other・substance=[statement] になり、
//   resolveOpener が「分類不能: LLM の開口語を尊重」（openerAllowed に かしこまりました を含む）に落ちていた＝**決めていなかった**。
//
// 実データ（365日・了承語で始まり「お願いします」を含むお客様の発言61件のうち、次のスタッフ発言が開口語で始まる19件）:
//   ・はい 12件 … 新しい中身が無い後押し
//       「了解しました！当日よろしくお願いいたします」「分かりました！お願いいたします🙇🏼‍♀️」
//       「承知しました。引き続きよろしくお願いいたします。」
//       「承知しました！時間的に厳しそうなので、写真またお願いします🙇🏻‍♀️」（写真はこちらが既に申し出た物）
//   ・かしこまりました 7件 … **新しい中身**がある
//       「わかりました、19:30に現地集合にてよろしくお願いします。」（日時）
//       「承知しました 19日夕方の鍵受け渡し宜しくお願いします」（日時）
//       「わかりました！追加でこちらも空いているか確認お願いしたいです」（追加の依頼）
//       「わかりました！あればお願いします！」（条件つきの依頼）
//   ＝19件中17件（89%）が「新しい中身があるか」で分かれる。
//
// ＝「お願いします」は動詞の形であって依頼の中身ではない。**新しい中身**（日時・追加の依頼・
//   こちらがまだ言っていない対象）があるかで、引き受け（かしこまりました）と後押し（はい）が分かれる。

/** 了承の言葉で始まる */
const ACK_HEAD_RE = /^\s*(?:承知(?:いた|致)?(?:しま)?した|かしこまりました|畏まりました|わかりました|分かりました|了解(?:いた|致)?(?:しま)?した|大丈夫です|りょうかいです)/;

/** 後押しの言葉（お願いします・ありがとうございます）。これが無ければこの場面ではない */
const PUSH_WORD_RE = /お願い(?:します|致します|いたします|しまーす|申し上げます)|ありがとうござい/;

/**
 * 新しい中身（＝引き受けが要る）。
 * ①日時・時刻の指定 ②追加・別件の依頼 ③条件つきの依頼 ④「〜して頂きたい／してほしい」の依頼形
 */
const NEW_SPECIFIC_RE = new RegExp([
  // 日時（19:30／19日夕方／9/12／明日／月曜）。「13:00〜13:30の枠」のようにこちらの文を引用した時も指定とみなす（安全側）
  "[0-9０-９]{1,2}\\s*[:：時]\\s*[0-9０-９]{0,2}",
  "[0-9０-９]{1,2}\\s*[\\/月]\\s*[0-9０-９]{1,2}",
  "(?<![0-9０-９])[0-9０-９]{1,2}\\s*日(?!割)",
  "明日|明後日|本日|今日|来週|今週|[月火水木金土日]曜",
  // 追加・別件の依頼
  "追加|こちらも|それも|他(?:に|にも)|別(?:の|で)|もう一?[件度]",
  // 条件つきの依頼
  "あれ(?:ば|したら)|ありましたら|(?:御座|ござ)いましたら|でしたら|次第",
  // はっきりした依頼形
  "(?:頂|いただ)きたい|(?:して|お)ほしい|して欲しい|下さい|ください|(?:頂|いただ)け(?:ます|れば|ると)",
].join("|"));

/** 依頼の対象になりうる物（これがあれば「こちらが既に言っているか」を見る） */
const REQUEST_OBJECT_RE = /写真|動画|画像|資料|間取り(?:図)?|見積(?:書|もり|り)?|御見積書|物件|お?部屋|書類|条件|確認|ピックアップ|ご案内|内覧|内見|申込|審査|連絡/g;

/**
 * 了承でも後押しでもない残りの文が「理由の節」だけか。
 * 「時間的に厳しそうなので、」（こちらの申し出のどちらを選ぶかの理由）は後押しのまま。
 * 「日付未定大阪市内で引越し業者は決めちゃってます。」（新しい情報の提供）は引き受けが要る。
 */
const REASON_TAIL_RE = /(?:ので|から|ため|けど|ですが|が)[、,。．]?\s*$/;
/** 了承・後押しの決まり文句（文ごと落とさず、この部分だけ剥がして残りを見る） */
const ACK_PHRASE_RE = /(?:承知(?:いた|致)?(?:しま)?した|かしこまりました|畏まりました|わかりました|分かりました|了解(?:いた|致)?(?:しま)?した|大丈夫です|りょうかいです)/g;
const PUSH_PHRASE_RE = /(?:引き続き|当日|何卒|是非|ぜひ)?\s*(?:よろしく|宜しく)?\s*お願い(?:します|致します|いたします|しまーす|申し上げます)|ありがとうござい(?:ます|まし た|ました)?/g;
function residualIsReasonOnly(text: string): boolean {
  const sentences = text.split(/\n|(?<=[。！!？?、,])/).map((s) => s.trim()).filter(Boolean);
  for (const s of sentences) {
    // 決まり文句だけ剥がして残りを見る（「同じくらいの感じでよろしくお願いします」の条件を落とさない）
    const rest = s.replace(ACK_PHRASE_RE, "").replace(PUSH_PHRASE_RE, "").trim();
    if (!rest) continue;
    if (REASON_TAIL_RE.test(rest)) continue;
    // 記号・絵文字を除いた中身が6字以内なら飾り（「写真また」「引き続き」「当日」）
    if (rest.replace(/[^\p{L}\p{N}]/gu, "").length <= 6) continue;
    return false;
  }
  return true;
}

export type AckPushVerdict = {
  /** 了承＋後押しだけ（新しい依頼ではない）＝開口語は「はい」 */
  push: boolean;
  reason: string;
  /** 判定に使った依頼の対象（こちらが既に言っている物） */
  objects: string[];
};

/**
 * お客様の発言が「了承＋こちらが既に言ったことの後押し」か。
 * recentStaffTexts は直近のこちらの発言（新しい順でも古い順でもよい・2〜3通で足りる）。
 */
export function resolveAckPush(
  customerText: string | null | undefined,
  recentStaffTexts: readonly (string | null | undefined)[] = [],
): AckPushVerdict {
  const t = (customerText ?? "").trim();
  const no = (reason: string): AckPushVerdict => ({ push: false, reason, objects: [] });
  if (!t) return no("no_text");
  if (!ACK_HEAD_RE.test(t)) return no("not_ack_head");
  if (!PUSH_WORD_RE.test(t)) return no("no_push_word");
  if (NEW_SPECIFIC_RE.test(t)) return no("new_specific");
  // 了承・後押し以外の文が理由の節でなければ、新しい情報を伝えている＝引き受けが要る
  if (!residualIsReasonOnly(t)) return no("new_statement");

  const objects = [...new Set((t.match(REQUEST_OBJECT_RE) ?? []))];
  if (objects.length === 0) return { push: true, reason: "ack_push_bare", objects: [] };

  // 対象がある時は、こちらが既にその話をしていれば後押し（新しい依頼ではない）
  const staff = recentStaffTexts.filter((s): s is string => !!s && !!s.trim()).slice(-3).join("\n");
  const unseen = objects.filter((o) => !staff.includes(o));
  if (unseen.length > 0) return { push: false, reason: `new_object:${unseen.join(",")}`, objects };
  return { push: true, reason: "ack_push_already_offered", objects };
}
