//   線は scripts/audit-opener-yesno-question.ts（人の手打ちの開口語）

/**
 * こちらが言った事・状況の確かめの質問か（「〜ってことですかね？」「〜という事でしょうか」「〜感じですか」「〜ないですよね？」）。
 * 「〜ありますか」「〜大丈夫でしょうか」「〜できますか」は依頼・日程の打診にもなり、人の返事も かしこまりました が多いので入れない
 * （人の手打ち 180日: 広い線 897通は なし599・かしこまりました198・はい100＝かしこまりました の多くは依頼の引き受け）
 */
export function isYesNoConfirmQuestion(text: string | null | undefined): boolean {
  const t = String(text ?? "").normalize("NFKC").trim();
  const last = t.split(/\n+/).filter(Boolean).pop() ?? "";
  return /(?:ってこと|って事|ということ|という事|って意味|感じ)(?:です|でしょう)?(?:か|かね|よね)?\s*[?？]|(?:ない|無い|ません)(?:です)?よね\s*[?？]?\s*[💦😭🥲]*$|ってことですかね|ということですかね/.test(last);
}
