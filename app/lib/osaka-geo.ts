function parseCoords(raw: string): Map<string, LatLon> {
  const m = new Map<string, LatLon>();
  for (const tok of raw.split(/[|\n]/)) {
    const t = tok.trim();
    if (!t) continue;
    const [name, la, lo] = t.split(/\s+/);
    const lat = Number(la), lon = Number(lo);
    if (name && Number.isFinite(lat) && Number.isFinite(lon)) m.set(name, { lat, lon });
  }
  return m;
}

