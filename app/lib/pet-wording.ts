// 2026-10-08 竹内「ペット相談可 → ペット飼育可能に書き換える」: 資料が「ペット相談可」の時、AIX・返信の本文では「ペット飼育可能」と書く（竹内さんの言い方）。
//   資料が「ペット不可」や「相談可」以外の時は触らない（この関数は「ペット相談可（能）」の形だけを置き換える）。
//   ⇒ 2026-10-09 竹内さん「ペットの部分だけペット飼育可能に統一」で、ペット可・ペット可能・ペットOK・ペット飼育可 等の可を言う形全部に広げた（下の PET_OK_RE）。
//      監査 scripts/audit-pet-wording-unify.ts（こちらの送信・AI の下書き・AIX の生成文に当てて前後を目で読む）
//
// ■ 実態（scripts/audit-r12-pet-wording.ts・こちらの送信 全期間）
//   「ペット相談可」は資料の書き方がそのまま本文に来た物（AIX の物件オススメ・ピックアップの箇条書き・手打ちの物件紹介）。
//   竹内さんの AIX は「相談可」16・「飼育可能」18 と割れていたが、竹内さんの決定で「ペット飼育可能」に揃える。
// ■ 置き換えない物（誤置換0の線）
//   ・聞く・確かめる形: 「ペット相談可能か」「ペット相談可能でしょうか」「ペット相談可能ですか」「ペット相談可能？」（相談できるかを確かめる文）
//   ・括弧の中の補足（「（猫2匹も相談可能）」「（大型犬ご相談可能）」）は「ペット」が前に無いので当たらない
//   ・「飼育可能（ペット相談可）」は括弧ごと落とす（「飼育可能（ペット飼育可能）」と重ねない）
//   ・「ペット相談可のお部屋」は「ペット飼育可能なお部屋」（「可能の」にしない）
// 戻すのは PET_WORDING=off（呼ぶ時に読む）

export function petWordingOn(env: Record<string, string | undefined> = typeof process !== "undefined" ? process.env : {}): boolean {
  return (env.PET_WORDING ?? "on").trim() !== "off";
}

/**
 * 2026-10-09 竹内さん「ペットの部分だけペット飼育可能に統一」: 説明の文も条件を並べる所も、可を言う形は全部「ペット飼育可能」に。
 *   対象: ペット可・ペット可能・ペットOK・ペット相談可（能）・ペット飼育可・ペット飼育相談可・ペット対応可・ペットの飼育も相談可能・ペット（猫）飼育可
 *   触らない: 否定（ペット不可・ペット飼育不可）・可否（ペット可否・ペット可・不可）・聞く形（ペット可能か・ペット可能でしょうか・ペット可ですか・？）・
 *             「ペット相談」（可が無い）・既に「ペット飼育可能」
 */
const PET_OK_RE = /ペット(?:の)?(?:飼育|対応)?(?:も)?(?:ご)?(?:相談)?(?:可能|可|OK|ＯＫ)(?!否|能?(?:か|でしょう|です(?:か|よね)|[?？])|[・/／、]?(?:不可|ＮＧ|NG)|能?の(?:詳細|記載|有無|可否))/g;
/** 「ペット（猫）飼育可」「ペット(小型犬)飼育可能」の括弧つき */
const PET_PAREN_OK_RE = /ペット([（(][^）)\n]{1,12}[）)])(?:の)?飼育(?:も)?(?:相談)?(?:可能|可)(?!否|能?(?:か|でしょう|です(?:か|よね)|[?？]))/g;
/** 「飼育可能（ペット相談可）」の括弧（前に飼育可能がある時だけ） */
/** 「飼育可能なペット相談可のお部屋」→「飼育可能なお部屋」（「飼育可能なペット飼育可能なお部屋」と重ねない・10/09 監査） */
const DUP_LEAD_RE = /(飼育可能)な?ペット(?:の)?(?:飼育)?(?:相談)?(?:可能|可)(?:の|な)?(?=お部屋|物件)/g;
const DUP_PAREN_RE = /(飼育可能)[\s　]*[（(]ペット(?:飼育)?(?:相談)?可(?:能)?[)）]/g;
const CANON = "ペット飼育可能";

export function normalizePetWording(text: string, env?: Record<string, string | undefined>): { text: string; fixed: string[] } {
  const src = String(text ?? "");
  if (!petWordingOn(env) || !/ペット/.test(src) || !/可|OK|ＯＫ/.test(src)) return { text: src, fixed: [] };
  const fixed: string[] = [];
  let out = src.replace(DUP_PAREN_RE, (m, a: string) => { fixed.push(m); return a; });
  out = out.replace(DUP_LEAD_RE, (m, a: string) => { fixed.push(m); return `${a}な`; });
  out = out.replace(PET_PAREN_OK_RE, (m, paren: string) => { const to = `ペット${paren}飼育可能`; if (m === to) return m; fixed.push(m); return to; });
  out = out.replace(PET_OK_RE, (m) => { if (m === CANON) return m; fixed.push(m); return CANON; });
  if (fixed.length) {
    // 「ペット相談可のお部屋」→「ペット飼育可能なお部屋」（「可能の」は不自然）。「可能のため」等はそのまま
    out = out.replace(/ペット飼育可能の(?=お部屋|物件|[0-9０-９]|[A-Za-zＡ-Ｚ]|戸建|マンション|アパート)/g, "ペット飼育可能な");
    // 「ペット可物件」→「ペット飼育可能な物件」・「ペット可条件」→「ペット飼育可能の条件」（元が「ペット飼育可能物件」の文は fixed が無いので触らない）
    out = out.replace(/ペット飼育可能(?=物件|お部屋|マンション|アパート|戸建)/g, "ペット飼育可能な");
    out = out.replace(/ペット飼育可能(?=条件)/g, "ペット飼育可能の");
    // 資料の「ペット相談・ペット対応可」→「ペット相談・ペット飼育可能」と重なる所は1つに（10/09 監査）
    out = out.replace(/ペット相談[・、]\s*ペット飼育可能/g, "ペット飼育可能");
  }
  return { text: fixed.length ? out : src, fixed };
}
