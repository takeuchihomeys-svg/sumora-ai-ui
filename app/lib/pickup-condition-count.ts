//   ・届けた行（AIX【物件ピックアップした】「…からピックアップさせて頂きました」）: フォームのある 63番で 0:22・1:17・2:13・3:5・4:5・5:1
//       ＝ **宣言より少なく**、お客様が特に気にしていた条件だけ（中央値1・エリアだけも多い）。条件の多い人ほど並べる数も少し増える（フォーム5つ→0〜4）。
//       例 10/05 同じ Yuki さん「大阪市内全域から1LDK〜2LDK・駅徒歩5分以内で…」（宣言の5つ→2つ）
//   ＝ 「2つまで」「最大3つ」「最大4個」のような固定の上限ではなく、お客様の条件の数と「宣言か届けた行か」で決める。
//
// 戻す: PICKUP_COND_COUNT=off（呼ぶ側の指示を旧の固定の数に戻す）

export function pickupCondCountOn(env: Record<string, string | undefined> = process.env): boolean {
  return (env.PICKUP_COND_COUNT ?? "on").trim().toLowerCase() !== "off";
}

const EMPTY_RE = /^(?:[\s　⇒→:：\-ー－]*)(?:特に(?:なし|無し|ない|ありません)?|なし|無し|ナシ|問わない|問いません|こだわりなし|こだわらない|指定なし|未定|どちらでも|なんでも|何でも)?[\s　。！!]*$/;

/** 条件のフォーム（①〜⑧）の書かれた欄の数（②家賃 ③間取り ④築年数 ⑥徒歩 は1つずつ・⑧その他は 、・ で分けて数える／①入居時期 ⑤エリア ⑦初期費用は数えない） */
export function countFormConditions(formText: string | null | undefined): number {
  // ⚠ NFKC は ①〜⑧ を数字に変えるので、欄に分けた後で値だけ正規化する
  const t = String(formText ?? "");
  if (!/②/.test(t)) return 0;
  const parts = t.split(/(?=[①②③④⑤⑥⑦⑧])/);
  let n = 0;
  for (const p of parts) {
    const mark = p.charAt(0);
    if (!"②③④⑥⑧".includes(mark)) continue;
    // 見出し（【…】・（…）・ご希望の〇〇）を外した値
    const raw = p.slice(1).normalize("NFKC");
    let v = raw.replace(/【[^】]*】/g, "").replace(/^[^⇒→:：]*[⇒→:：]/, "");
    if (v === raw) v = v.replace(/^\s*(?:ご希望の?)?(?:家賃|間取り|広さ・間取り|築年数|駅からの徒歩分数|駅徒歩分数|徒歩分数|その他(?:ご要望あれば)?)[^\s]*\s*/, "");
    v = v.replace(/\n+/g, " ").trim();
    if (EMPTY_RE.test(v)) continue;
    if (mark === "⑧") n += v.split(/[、,・\/／]|\s{2,}/).map((s) => s.trim()).filter((s) => s && !EMPTY_RE.test(s)).length;
    else n += 1;
  }
  return n;
}

/** 条件らしい語（エリア・名前・敬語の切れ端を数えないため） */
const COND_TOKEN_RE = /[0-9０-９]+(?:\.[0-9]+)?\s*(?:万|円|分|年|帖|畳|㎡|平米|m²|階)|[0-9]?(?:K|DK|LDK|R|SLDK)(?![a-z])|築|徒歩|ペット|飼育|駐車|バス|トイレ|風呂|独立洗面|オートロック|宅配|2口|コンロ|浴室乾燥|室内洗濯|ウォークイン|クローゼット|広め|広い|綺麗|きれい|リノベ|新築|築浅|RC|鉄筋|鉄骨|角部屋|南向き|日当たり|二人|2人|お2人|同棲|ファミリー|一人暮らし|女性|入居可能|初期費用|敷金|礼金|管理費込|家賃|インターネット|ネット無料|生活保護|保証人|分譲|マンション|戸建|カウンターキッチン|防音|シャワー|エアコン|1階|2階以上|上階/;

/** ピックアップの1行（宣言・届けた行）に添えた条件の数（エリア・お客様の名前は数えない） */
export function countEchoedConditions(line: string | null | undefined): number {
  let s = String(line ?? "").normalize("NFKC");
  // エリアの後（「〜全域から」「〜周辺から」「〜エリアから」…）だけを見る。無ければ行全体
  const m = s.match(/^.*(?:全域|周辺|エリア|沿線|沿い|市内|府内|区|市|駅|方面|付近|近辺|圏内|以内のエリア)(?:から|より)、?/);
  if (m) s = s.slice(m[0].length);
  s = s.split(/ピックアップ/)[0] ?? "";
  // 名前と決まった語（〇〇さんご希望の・〇〇さんにオススメできる・お部屋・ご条件で）
  // 「〜以内で〇〇さん」の「で」で切る（名前の語に条件を巻き込まない）・間取りの並び（1R・1K）は1つに数える
  s = s.replace(/(以内|以下|以上|程|程度|可能|可|付き|付|別|込み|まで|円|K|R)(?:で|の)(?=[^\s・、]{1,20}(?:さん|様))/g, "$1・")
    .replace(/([0-9]?(?:SLDK|LDK|DK|K|R))(?:・|、|か|または|〜|~)(?=[0-9]?(?:SLDK|LDK|DK|K|R))/g, "$1/");
  s = s.replace(/[^\s・、]{0,20}(?:さん|様)(?:達|たち)?(?:ご希望の|にオススメ(?:でき|出来)る|の)?/g, "・")
    .replace(/(?:ご希望の)?(?:ご)?条件(?:に(?:合った|近い))?(?:で)?/g, "・")
    .replace(/お部屋(?:を|全て)?/g, "・").replace(/オススメ(?:でき|出来)る/g, "・");
  return s.split(/[・、]|(?<=以内|以下|以上|程|程度|可能|可|付き|付|別|込み)(?:の|で)/).map((x) => x.trim()).filter((x) => x && COND_TOKEN_RE.test(x)).length;
}

/**
 * 指示の1段（AIX【物件ピックアップした】の届けた行）。固定の上限ではなく、お客様の条件と竹内さんの型で決める。
 *   formCount: お客様の条件の数（分からなければ null）
 */
export function deliveredPickupConditionRule(formCount: number | null): string {
  const base = "・添える条件の数は決め打ちしない（竹内さんの届けた行は、初回の宣言で並べた条件より少なく、お客様が特に気にしていた条件＝家賃の上限・間取り・ペット・駐車場・広さ・二人暮らし・初期費用 等だけを添える。竹内さんの実績は0〜2つが8割・エリアだけの行も多い）。宣言の条件を全部並べ直さない";
  if (formCount == null) return base;
  return `${base}（この方の条件は${formCount}つ。届けた行はそのうち特に気にしていた物だけ＝${formCount}つ全部は並べない${formCount <= 1 ? "・エリアだけでもよい" : ""}）`;
}

