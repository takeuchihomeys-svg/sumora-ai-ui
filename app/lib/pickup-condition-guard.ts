// 2026-09-19 一度 stripUngroundedConditions（区切りの単位で落とす）を作り、
// 設計知見「落とす仕組みは過去の全件に当てて目で読む」に従って実送信221通に当てたところ、
// **15通（6.8%）が書き換わり、そのうち多くが文の破壊か誤削除**だった。実物:
//   旧「ウォークインクローゼットが備わった広々としたお部屋ピックアップしお送り…」
//   新「が備わった広々としたお部屋ピックアップしお送り…」                      ← 文頭が壊れる
//   旧「2面鏡以上の独立洗面台が備わった審査通過しやすいお部屋…」
//   新「台が備わった審査通過しやすいお部屋…」                                  ← 壊れる
//   旧「…Yさんご希望のご条件に合ったバストイレ別・駐車場あり・保証人不要…」
//   新「…Yさんご・保証人不要…」                                                ← 壊れる
// 誤削除の中身も、お客様が**条件フォームの画像**で送った条件（バストイレ別・駐車場）が
// 「テキストに残っていない」だけで根拠なし扱いになっていた。
//
// → **検出はする（findUngroundedConditions は94%の精度）が、落とさない**。
//   スタッフへの注意（buildUngroundedNotice）としてテキストボックスの外に出す。
//   設計知見「落としすぎの方が気付きにくい」「入口は厳しく、出口は緩く」。
//   本当に直すなら、根拠の側（条件フォーム画像の読み取り結果を登録条件に入れる）を厚くする。
