// app/lib/pickup-condition-guard.ts
// ピックアップ宣言（これから探す条件を書く行）に、**お客様が言っていない設備条件**が混ざるのを止める（純関数）。
//
// 2026-09-19 竹内（慶次事例）「ペット飼育等お客さんいうていないのにペット飼育とでてしまった。
//   ここも根本的な部分みつけて改善」
//   慶次さんの新条件は「中央大通りより北側・ミナミ方面は避けたい」なのに、下書きは
//   「かしこまりました！！／**ペット可条件で**お部屋ピックアップさせて頂きます！！」だった。
//   出所はナレッジ（ai_reply_knowledge）の**例文**で、
//     principle「お客様が具体的な物件条件（駅徒歩・間取り・**ペット可**など）を追加提示した場合は…」
//     例外「**あと、ペット可能でお願いします**」（他顧客の発言がそのまま埋め込まれている）
//   慶次さんの場面がまさに「条件の追加提示」なので引かれ、**例として書かれた条件を実際の条件と取り違えた**。
//
// 【線の引き方（実送信で測った）】
//   本文のどこかに出る条件語で測ると線が引けない（オートロック26%・宅配ボックス10%・角部屋2%しか
//   お客様が言っていない＝こちらが物件の**設備説明**として書くため）。
//   「**ピックアップ宣言の行**に出る条件語」だけに絞ると 268件中 252件（**94%**）がお客様の発言に根拠あり。
//   根拠なし16件の中身: ペット9件は「ペットは猫ちゃんですか？犬ちゃんですか？」の**質問文**、
//   バストイレ別5件は条件フォーム画像（テキストに残らない）、独立洗面2件は物件の設備説明。
//   → 根拠は「お客様の発言 ∪ 登録条件」で見て、**否定の項目は根拠にしない**（申込フォームの
//     「ペット飼育有無 無し」を根拠にすると、まさに慶次さんの事故になる）。

/** ピックアップ宣言の行（これから探す条件を書く所） */
export const PICKUP_LINE_RE =
  /(?:ピックアップ|お探し|探させて|お調べ|探して)[^\n]{0,20}(?:させて(?:頂|いただ)き|します|いたします|致します|お送り)/;

/** お客様が言う種類の設備条件語（こちらが設備説明で書く語も入るが、宣言行に限れば根拠が要る） */
export const COND_WORDS = [
  "ペット", "駐車場", "楽器", "事務所", "二人入居", "ルームシェア", "同棲", "喫煙",
  "バストイレ別", "独立洗面", "オートロック", "宅配ボックス", "角部屋", "分譲", "ウォークインクローゼット",
] as const;

/**
 * 否定の項目（申込フォームの「ペット飼育有無 無し」「駐車場（台数）0」等）＝根拠にしない。
 * 2026-09-19 監査で見つけた誤り: 裸の `0` を入れると「家賃5〜1**0**万円」に当たって
 *   同じ行の別の条件（同棲可）まで否定扱いになった。数字の否定は「台数」等の器と一緒の時だけ見る。
 */
const NEGATED_NEAR_RE =
  /無し|なし|ナシ|不要|ありません|(?<![0-9０-９])無い|×|(?:台数|数|件数)[）)\s]*[:：]?\s*[0０](?![0-9０-９])/;
/** 語のすぐ後ろだけを見る幅（「ペット飼育有無 無し」「駐車場（台数）0」が入る長さ） */
const NEGATION_WINDOW = 16;

/**
 * その語がお客様の発言・登録条件に根拠を持つか。
 * 語の**すぐ後ろ**に否定の印があれば根拠にしない（行全体で見ると別の条件まで巻き込む）。
 */
export function conditionGrounded(word: string, sources: ReadonlyArray<string | null | undefined>): boolean {
  for (const src of sources) {
    const text = String(src ?? "");
    let from = 0;
    for (;;) {
      const idx = text.indexOf(word, from);
      if (idx < 0) break;
      from = idx + word.length;
      const win = text.slice(idx, idx + word.length + NEGATION_WINDOW);
      if (NEGATED_NEAR_RE.test(win)) continue;   // 「ペット飼育有無 無し」は根拠にしない
      return true;
    }
  }
  return false;
}

export type UngroundedHit = { word: string; line: string };

/** ピックアップ宣言の行にある、根拠の無い設備条件語 */
export function findUngroundedConditions(
  draft: string,
  sources: ReadonlyArray<string | null | undefined>,
): UngroundedHit[] {
  const out: UngroundedHit[] = [];
  for (const line of String(draft ?? "").split("\n")) {
    if (!PICKUP_LINE_RE.test(line)) continue;
    // 質問文（「ペットは猫ちゃんですか？」）は条件の宣言ではないので触らない
    if (/[?？]/.test(line)) continue;
    for (const w of COND_WORDS) {
      if (!line.includes(w)) continue;
      if (conditionGrounded(w, sources)) continue;
      out.push({ word: w, line: line.trim() });
    }
  }
  return out;
}

/** 見つけた語をスタッフへの注意文にする（テキストボックスの外に出す・本文は変えない） */
export function buildUngroundedNotice(hits: ReadonlyArray<UngroundedHit>): string {
  if (hits.length === 0) return "";
  const words = [...new Set(hits.map((h) => h.word))];
  return `⚠ 会話に根拠の無い条件が入っています: ${words.join("・")}\n`
    + `　お客様の発言にも登録条件にもありません（ナレッジ・手本の例文から混ざった可能性）。送信前に確かめてください。`;
}

