/** DB の学習ルール（ai_prompt_rules）で外す行の目印（7c600c23・46195788）。
 *  ⚠ 2026-10-08 11:03Z に本番の2本は新しい文に書き換え済み（rules_fix.sql・竹内さん Q7「依頼は受けてから・質問は答えから」）。
 *    目印は旧の文にしか無いので、書き換え後の文はそのまま通る（テストで固定）。旧の文が戻った時（控えから戻した時）だけ外れる。
 *    scripts/.replay-out/r11-rules-retire.sql は流さない（10/08 調整役） */
export const PROMPT_R11_DROP_LINES: ReadonlyArray<string> = [
  "必ず承認の一言を挟むことで",
  "「確認出来次第お送りします」等の次アクション文を必ず挿入し",
];

export function applyPromptR11(text: string, enabled = promptR11Enabled()): { text: string; hits: number } {
  if (!enabled || !text) return { text, hits: 0 };
  let s = text, hits = 0;
  for (const [from, to] of PROMPT_R11_REPLACEMENTS) if (s.includes(from)) { s = s.split(from).join(to); hits++; }
  if (PROMPT_R11_DROP_LINES.some((m) => s.includes(m))) {
    s = s.split("\n").filter((l) => { const drop = PROMPT_R11_DROP_LINES.some((m) => l.includes(m)); if (drop) hits++; return !drop; }).join("\n");
  }
  return { text: s, hits };
}
