/** user に渡す材料（会話・ブレインの希望条件・スタッフの補足メモ）。名前が無ければ「名前は書かない」 */
export function buildPropertySearchUser(o: { name: string; history: string; brainPreferences?: string | null; staffNote?: string | null }): string {
  return [
    o.name ? `お客様名: ${o.name}` : "お客様名: 不明（名前も「お客様」も書かない）",
    o.staffNote?.trim() ? `【スタッフの補足メモ（今回探す条件・最優先）】${o.staffNote.trim()}` : "",
    o.brainPreferences?.trim() ? `【ブレインが読んだご希望（参考・会話で言っていない物は書かない）】${o.brainPreferences.trim()}` : "",
    o.history,
    "\n上の会話の最後のお客様の発言を受けて、ピックアップしてお送りすると約束する1通を作ってください。",
  ].filter(Boolean).join("\n");
}

/** LLM が失敗・空の時の1通（手打ちの最小の型） */
export function propertySearchFallback(name: string): string {
  return `かしこまりました！！\n${name ? `${name}に` : ""}オススメできるお部屋ピックアップしてお送りさせて頂きます😊！！`;
}

/**
 * 探す約束の1通に要らない物（送る前の注意・本文は変えない）。
 * @param conversationText 会話（お客様が言った額・物件名は書いてよい）
 */
//   線（スタッフの手打ちの約束 517通に当てて決めた・scripts/audit-unpressed-aix-text.ts --check=ps）:
//     号室 0通・「お客様」1通（「他のお客様」を除いて 0）・形の記号 0 → 注意に残す
//     内覧の話 32・見積 22・確認の約束 7・会話に無い額 67（お客様の「14」をスタッフは「14万円以内」と書く）→ 手打ちでも普通に書く＝注意にしない（指示の禁止だけ）
export function propertySearchTextIssues(text: string): string[] {
  const t = text ?? "";
  const issues: string[] = [];
  if (/\d+\s*号室/.test(t)) issues.push("号室");
  if (/(?<![別他]の|ほかの)お客様(?:に|が|の|へ|は)/.test(t)) issues.push("「お客様」と呼んだ");
  if (/(?:^|\n)\s*[「]?[①②③]\s*「|」\s*\n\s*[①②③]/.test(t)) issues.push("形の記号の漏れ");
  return issues;
}
