const NFKC = (s: string) => (s ?? "").normalize("NFKC");
/** 家賃（前家賃・翌月分・〇月分の家賃）が含まれているか、の形 */
const RENT_INCLUDED_RE = /(?:前家賃|翌月分?の?家賃|[0-9]{1,2}月分の?家賃|家賃)[^\n。]{0,8}(?:(?<!振り?)込み?|(?<!振り?)込ん|含ま|含め|含む|入って|入る)/;
/** 質問の形（「ですよね」「認識でしょうか」「ってこと」も） */
const QUESTION_RE = /[?？]|ですか|ますか|でしょうか|かね|よね|のか|ってこと|認識/;
/**
 * 「家賃込みか」以外の話（初期費用の中身・家賃だけで住めるか・日割・家賃の条件・値引き・支払い方法）。これがあれば当てない
 * （AIX【初期費用について】・物件ピックアップ・見積書送る 等の今までの判断に任せる）
 */
const OTHER_TOPIC_RE = /管理費|共益費|込み込み|だけ|のみ|住め|入居(?:でき|出来)|入れ(?:る|ます)|何が|なにが|内訳|他に|ほかに|別途|別で|とは別|追加|上乗せ|火災保険|鍵交換|保証料|敷金|礼金|クリーニング|日割|安く|値引|交渉|分割|カード|書き換え|項目|[0-9]\s*万[^\n。]{0,3}(?:以内|以下|まで)|円(?:以内|以下|まで)|ならない|なりませんか/;
/** 条件フォーム（①【ご入居の時期】⇒…） */
const FORM_RE = /【[^】]*(?:ご希望|初期費用|ご入居)[^】]*】|[①-⑩][^\n]{0,12}⇒/;

/** 「家賃込みですか」だけを聞いている1通か（画像の読み取り文・条件フォームは見ない） */
export function isRentIncludedQuestion(unit: string | null | undefined): boolean {
  const t = NFKC(unit ?? "").trim();
  if (!t || /^\[(?:画像|動画|スタンプ|ファイル)\]/.test(t)) return false;
  if (FORM_RE.test(t)) return false;
  if (!RENT_INCLUDED_RE.test(t) || !QUESTION_RE.test(t)) return false;
  if (OTHER_TOPIC_RE.test(t)) return false;
  return true;
}

/**
 * お客様の今回の連投（改行・通の区切りでつないだ物）が「家賃込みか」の質問だけか。
 * 家賃込みの質問が1通以上あり、他の通は質問・依頼の形でない（お礼・相づち・「ありがとうございます」等）時だけ true。
 * 他に質問・依頼（内覧・見積もり・空き・別の費用）がある連投は、ブレインの判断のまま（入口で AIX を外さない）
 */
export function rentIncludedOnlyTurn(turnText: string | null | undefined): boolean {
  const units = NFKC(turnText ?? "").split(/\n⁣\n|\n/).map((u) => u.trim()).filter((u) => u && !/^\[(?:画像|動画|スタンプ|ファイル)\]/.test(u));
  if (!units.some((u) => isRentIncludedQuestion(u))) return false;
  return units.every((u) => isRentIncludedQuestion(u) || (!QUESTION_RE.test(u) && !OTHER_ASK_RE.test(u)));
}
/** 質問の形でなくても依頼・希望になっている通（「見積もりお願いします」「内覧したいです」） */
const OTHER_ASK_RE = /お願い(?:し|致|いた)?(?:ます|したい)|ください|下さい|頂け|いただけ|欲しい|ほしい|したい|希望|見積|内覧|内見|空い|募集/;

