//   ちゃんとここはブレインで判断できるように。根拠のないことなど AIX 回答できるから、そこの仕組に着眼して」
//
// 【出所】DeepSeek 経路の返信生成が「室内写真は現在ご用意出来ていない為、私の方で撮影しお送りさせて頂きます」と
//   根拠の無い文を書いた。出口（final-check V16）で止める形は入れたが、そもそも**返信文で答える場面ではない**:
//   スタッフが AIX【物件確認した】→「室内写真を確認した」ピッカーで、手元の写真・室内イメージURL を物件名とあわせて送る仕組みがある。
//   ブレインがこの場面で AIX をセットしていなかった（brain_decision_logs 365日: 写真の依頼への interior_photo の提案 0回）。
//
// 【実送信で引いた線】（scripts/audit-photo-request-aix.ts・365日・広い候補149通を全部目で読んだ）
//   お客様の写真の依頼にスタッフが返した形の多数派は「室内イメージURL／画像を送る」（AIX ピッカー＋手書きで同じ形）、
//   次が「撮影して後日送る」、「建築中等の理由付きで無い」。根拠なしの「ご用意出来ていない」断定は 0通。
//   → 返信文では写真の有無・撮影の約束を作らせない（受付の一文まで）。写真・URL は AIX から。
//
// 【当てる／当てない】（反証で見つかった誤当たりを実物で外した）
//   当てる: 「室内の写真ありますか」「お部屋の画像ありますでしょうか」「これ室内写真欲しいです」「ここの内見の動画もらっていいですか」
//           「URLとかありますでしょうか」「室内の雰囲気って見れたりしますか」「内装見してもらっていいですか」「写真お願いできますか」
//   当てない: 書類の写真（身分証・内定通知・明細書・申込書の記入箇所・顔写真・契約書）／フォームの語（貼り付け欄・テンプレ・申請URL）／
//            お客様が自分で送る話（「写真送っても添付はできない」「写真送っていないもう2件を送らせて」）／
//            写真を指して別の事を聞く（「写真の二件お願いしたい」「上記の写真の中で8月入居可能なのは」「この写真のような物件があれば」
//            「画像があったので確認お願い」）／URL が開けない苦情だけ（「URLが見れなくて」）／
//            お礼・受領（「写真ありがとうございます」「拝見しました」）は**文単位**で外す（同じ発言の別の文に依頼があれば依頼）／
//            [画像] で始まる通（書き起こし）
//   裸の「写真お願いします」（室内・物件の語が無い）は、短い文（24字以内）で依頼・質問の形の時だけ当てる
//   （反証: 裸の「写真＋お願い／もらえ／可能」を無条件に当てると申込書類・明細書の依頼が混ざる）。
//
// 四者同名: ブレインの場面（aix-scene-evidence S11）・会社の事実（company-facts room_photo）・生成プロンプト（generate-reply）・
//   出口の検査（company-fact-guard）が同じこの関数で「写真の依頼」を決める。

/** 写真・動画・URL の名詞 */
const PHOTO_NOUN = "(?:写真|画像|動画|ムービー|イメージ|フォト|ＵＲＬ|URL|url|Url|リンク|ホームページ|ＨＰ|HP)";
/** 室内・物件を指す語（これが同じ文に無い裸の「写真お願い」は下の短文の形だけ） */
const SUBJECT_RE = /室内|お部屋|部屋|内装|内部|外観|外見|物件|ここ|これ|こちら|こっち|そこ|それ|そちら|そっち|建物|マンション|ハイツ|コーポ|レジデンス|ハイム|メゾン|アパート|号室|間取|内見|内覧|雰囲気|様子|上記|他の|別の|ほかの|全部屋|各部屋|キッチン|風呂|トイレ|バス|洗面|ベランダ|玄関|収納|眺め|景色/;
/** 依頼・質問の形（名詞の後ろ 14字以内） */
const REQUEST_TAIL = "[^\\n。！!？?]{0,14}?(?:欲し|ほし|ください|下さい|頂け|いただけ|頂きたい|いただきたい|頂いても|いただいても|頂いて|いただいて|もらえ|貰え|もらって|貰って|もらう|もらいたい|貰いたい|ありま|ござい|ないです|無いです|ない(?:でしょ|んです|ですか|の|か)|見たい|見れ|見せ|見して|見られ|送って|送れ|送付|お願い|拝見|可能|いけ|くれ|教え|頂戴|ちょうだい|貼って|載せて|あれば|あったら)";
const REQUEST_RE = new RegExp(`${PHOTO_NOUN}${REQUEST_TAIL}`, "i");
/** 裸の短文（室内・物件の語なし）で当てる形は、はっきりした依頼・質問だけ */
const BARE_REQUEST_RE = new RegExp(
  `(?:写真|画像|動画|ＵＲＬ|URL|url|リンク)[^\\n。！!？?]{0,10}?(?:ありま(?:すか|すでしょうか|せんか|すでしょ)|ござい(?:ますか|ますでしょうか|ませんか)|欲し|ほし|ください|下さい|いただけ|頂け|いただきたい|頂きたい|いただいて|頂いて|いただいても|頂いても|もらえ|貰え|もらって|貰って|お願い|送って)`,
  "i",
);
const BARE_MAX_LEN = 24;
/** 「室内の雰囲気って見れたりしますか」「内装見してもらっていいですか」（名詞が無い形） */
const LOOK_INSIDE_RE = /(?:室内|内装|お部屋の中|部屋の中|中の様子|中の雰囲気)(?:の)?(?:雰囲気|様子)?[^\n。！!？?]{0,6}(?:見れ|見せ|見して|見たい|見ること|見られ)/;

/**
 * 同じ文にあれば当てない（別の書類・お客様が送る側・写真を指して別の事を聞く・URL が開けない苦情）。実物は上の注記。
 * ⚠ 「の部屋」「の物件」のような一般語は、写真の名詞に付いた形（「写真の物件」「写真の二件」「写真の中」）だけ外す
 *   （初版で裸の「の物件」を外して「こちらの物件お部屋の写真ありますか」「ここの部屋の写真はありますか」を落としていた）
 */
const EXCLUDE_SENTENCE_RE = new RegExp([
  "身分証|パスポート|免許|保険証|本人確認|証明書|証明写真|顔写真|履歴書|契約書|契約|申込書|申し?込|申請|再発行|フォーム|フォーマット|届",
  "報告|貼り付け|貼付|欄|テンプ|明細|通知|記入|添付|同封|署名|サイン|印鑑|マイナンバー|学生証|保険|カード|クレジット|振込|決済|領収|請求|支払",
  "見積|審査|承認|給与|源泉|通帳|残高|在籍|内定|名簿|印刷|プリント|保存|スクショ|スクリーンショット|記載|アクセス|飛んで",
  // お客様が自分で送る側・送った物を指す
  "送っても|送らせて|送りますね?|送ります|送っておき|送っていない|送ってない|送りました|送らせていただ|お送りした|お送りいただいた|お送り頂いた|送っていただ|送って頂|送ってくださった|送った",
  "いただいた(?:写真|画像|動画|URL)|頂いた(?:写真|画像|動画|URL)|(?:写真|画像|動画)(?:の|も)?(?:通り|とおり)",
  // 写真を指して別の事を聞く・物件探し
  "(?:写真|画像|動画)の(?:物件|お?部屋|やつ|方|件|中|二件|三件|[0-9０-９]+件|[0-9０-９]+枚目)|(?:写真|画像)(?:の|み)(?:よう|たい)な|枚目",
  "入居可能|入居でき|入居出来|空(?:き|いて)|募集|探し|さがし|ピックアップ|確認お願い|確認して(?:ほし|欲し|頂|いただ|もらえ)",
  // URL・画像が開けない苦情だけの文（依頼は別の文で見る）
  "見れな|見られな|見えな|開けな|開かな|読み込|表示され|エラー|見れました|見れてます|見えます|届いて|届きま|受け取",
  // 内覧に行く話（「内見の動画」は残す）
  "見に行|行きたい|行ってみたい|行ってみよう",
].join("|"), "i");
/** お礼・受領（文単位で外す。同じ発言の別の文に依頼があれば依頼） */
const ACK_RE = /ありがとう|拝見しました|拝見いたしました|見ました|確認しました|確認いたしました|届きました|助かります|了解|承知|わかりました|分かりました|かしこまりました/;
/** 画像の書き起こし（[画像] で始まる通）は当てない（company-facts と同じ線） */
const IMAGE_UNIT_RE = /^\s*\[(?:画像|動画|スタンプ|ファイル)\]/;
/** 通の区切り（reply-context.MSG_SEP と同じ。依存ゼロを保つためここで持つ） */
const UNIT_SEP_RE = /\n⁣\n/;

/** 1文（区切り: 改行・空白・。！？）が写真の依頼か */
export function isRoomPhotoRequestSentence(sentence: string): boolean {
  const s = (sentence ?? "").normalize("NFKC").trim();
  if (!s) return false;
  const body = s.replace(ACK_RE, "");
  if (ACK_RE.test(s) && !REQUEST_RE.test(body) && !LOOK_INSIDE_RE.test(body)) return false;
  if (EXCLUDE_SENTENCE_RE.test(s)) return false;
  if (LOOK_INSIDE_RE.test(s)) return true;
  if (REQUEST_RE.test(s) && SUBJECT_RE.test(s)) return true;
  return s.length <= BARE_MAX_LEN && BARE_REQUEST_RE.test(s);
}

/** 文に分ける（細かい: 改行・空白・句点・！？／粗い: 改行だけ。「リンク？みたいなの欲しい」は粗い方で拾う） */
function fineSentences(text: string): string[] {
  return (text ?? "").split(/[\n。！!？?\s　]+/).map((s) => s.trim()).filter(Boolean);
}
function lineSentences(text: string): string[] {
  return (text ?? "").split(/\n/).map((s) => s.trim()).filter(Boolean);
}

/** 1通の中で当たった文（無ければ null）。粗い方は文中の「？」（「リンク？みたいなの欲しい」）を外してから見る */
function hitInUnit(unit: string): string | null {
  return fineSentences(unit).find(isRoomPhotoRequestSentence)
    ?? lineSentences(unit).map((l) => l.replace(/[？?](?=\S)/g, "")).find(isRoomPhotoRequestSentence)
    ?? null;
}

/**
 * 物件名らしい語（カタカナ3字以上＋部屋・物件・号室・室内・内装）が文にあるか。
 * 持込物件（こちらの送付0）の「ビオラコート幸町の部屋の写真ありますか」（0133b787）を場面で拾うため（aix-scene-evidence S11 が使う）
 */
export const PROPERTY_NAME_LIKE_RE = /[ァ-ヶー]{3,}[一-龥ぁ-ん０-９0-9]{0,6}(?:の)?(?:お?部屋|物件|号室|室内|内装)/;

/**
 * お客様の発言（1通、または未返信の連投を結合した文字列）が室内の写真・動画・URL の依頼か。
 * 通ごと（\n⁣\n 区切り）に見て、[画像] で始まる通は当てない。1文でも依頼の形があれば true。
 */
export function isRoomPhotoRequest(customerText: string | string[] | null | undefined): boolean {
  return roomPhotoRequestSentence(customerText) !== null;
}

/** 当たった文（監査・テスト用。無ければ null） */
export function roomPhotoRequestSentence(customerText: string | string[] | null | undefined): string | null {
  const arr = Array.isArray(customerText) ? customerText : [customerText ?? ""];
  for (const t of arr) {
    for (const unit of (t ?? "").split(UNIT_SEP_RE)) {
      const u = unit.trim();
      if (!u || IMAGE_UNIT_RE.test(u)) continue;
      const hit = hitInUnit(u);
      if (hit) return hit;
    }
  }
  return null;
}

/** 「内見の動画」「内覧の写真」の語を外した文（内覧希望の判定に渡す用。写真の依頼を内覧希望と読まないため） */
export function stripPhotoWordsForViewing(text: string): string {
  return (text ?? "").replace(/(?:内見|内覧)(?:の)?(?:動画|写真|画像|イメージ)/g, "");
}
