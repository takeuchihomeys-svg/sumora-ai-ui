// app/lib/selection-claim.ts
// 「こちらが確かめていない**選び方の主張**」を落とす（純関数・DB 依存なし）。
//
// 2026-09-18 竹内「これでテンプレートの文も実際生成された文のように質高いのかな？」
//   本番検証でテンプレート生成が2回とも
//     「前回お送りさせて頂いた物件とは**重複しないよう選定しております**😊！！」
//     「前回お送りした物件とは**重複しないよう**、新着で条件に近いお部屋を中心に**選ばせて頂いております**！！」
//   と書いた。システムは重複の有無を知らない（物件リストは別で添付される）ので、これは**やっていないことの主張**。
//
// 実データ（365日・スタッフ実送信 11,703通）で線を引いた:
//   ・「重複」を含む通は **9件**。中身は例外なく**逆**で、「重複しています、すみませんが」と正直に断る形
//       「過去にお送りさせていただいた重複する物件もございますがお手隙の際にご査収ください」
//       「以前お送りさせていただきましたお部屋と重複するお部屋もございますが」
//       「重複する物件2件ございますが」「以前お送りさせていただいたお部屋と重複しますが」
//   ・「重複しない」**0件** ／「被らない・かぶらない」**0件** ／「重ならない」**0件**
//   ・「選定」**0件** ／「選ばせて頂いて・選ばせていただいて」**0件**
//   ＝ こちらは「重複していません」とは言わない。言うのは「重複していますが」の方だけ。
//
// 設計知見「実データで前提が崩れた使用例が0件なら決定論で落として安全」に従い、**0件の形だけ**を落とす。
// 正直な断り（「重複しますが」「重複する物件もございますが」）は**残す**。

/**
 * こちらが確かめていない選び方の主張（実送信0件）。**節の単位**で落とす。
 * 前後とも読点を越えない（越えると「、新着で条件に近いお部屋を中心に…」のような
 * 落とす必要のない節まで飲み込んで、文が丸ごと消える）
 */
const UNFOUNDED_SELECTION_RE =
  /[^。！!\n、]{0,30}(?:重複しない|重複せ(?:ず|ぬ)|重複が?ない|被らない|かぶらない|重ならない|選定(?:して|させて|いた)|選定済み)[^。！!\n、]{0,20}/g;

/** 「重複しますが」＝正直な断り（実送信9件）。落とさない */
const HONEST_OVERLAP_RE = /重複(?:する|し(?:ます|て(?:い|お)ります))/;

export type SelectionClaimResult = { text: string; removed: string[] };

/**
 * 「重複しないよう選定しております」等、こちらが確かめていない選び方の主張を落とす。
 * ・正直な断り（重複しますが／重複する物件もございますが）は触らない
 * ・落として行が空になったらその行ごと消す
 * ・文が全部消えるなら元のまま返す（安全側）
 */
export function stripUnfoundedSelectionClaim(text: string): SelectionClaimResult {
  const src = text ?? "";
  if (!src.trim()) return { text: src, removed: [] };
  const removed: string[] = [];

  const lines = src.split("\n").map((line) => {
    if (HONEST_OVERLAP_RE.test(line) && !/重複しない|重複せ(?:ず|ぬ)|重複が?ない/.test(line)) return line;
    let out = line.replace(UNFOUNDED_SELECTION_RE, (m) => { removed.push(m.trim()); return ""; });
    if (!removed.length) return line;
    // 主張だけの行だった場合は行ごと落とす／残りの読点・接続を整える
    out = out.replace(/^[\s、,。！!]+/, "").replace(/[\s、,]+$/, "").trim();
    return out;
  });

  if (!removed.length) return { text: src, removed: [] };
  const joined = lines.filter((l, i) => l.trim() !== "" || src.split("\n")[i].trim() === "")
    .join("\n").replace(/\n{3,}/g, "\n\n").trim();
  if (!joined) return { text: src, removed: [] }; // 全部消えるなら触らない
  return { text: joined, removed };
}

