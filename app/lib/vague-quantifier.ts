// 物件名を並べた直後の「複数の物件について」等、**数のまとめ語**を落とす（純関数・DB 依存なし）。
//
// 2026-09-17 竹内（a🤫 事例）「**複数の** 等いれない。なんでこんなにはいってしまっているのか。根本的な部分改善する」
//
// AI 下書き:
//   「かしこまりました！！／生野西一丁目戸建・阪南町3丁目3L戸建て・天神ノ森3SLDK、**複数の物件について**
//     募集状況確認させて頂きます！！／本日は管理会社の営業時間が終了しておりますので、明日一番で確認しご連絡させて頂きます😌！！」
// 実送信:
//   「…生野西一丁目戸建・阪南町3丁目3L戸建て・天神ノ森3SLDK、**の物件について**募集状況確認させて頂きます！！…」
//
// 実データ（365日・募集状況の確認を宣言したスタッフ実送信208通）:
//   ・「複数の物件／複数のお部屋」… **0件**
//   ・物件名を「・」で並べた通で数（複数の・〇件）を書いた例 … **0件**
//   ・件数（「お送り頂きました3件」）を書くのは**物件名を並べない時**だけ … 32件
//   ＝名前を書いたら数は書かない。名前を書かない時だけ件数。
//
// 「なんで入るのか」（竹内さんの問い）の答え:
//   ①指示に「複数件なら件数を明示」とあり、物件名を並べた時まで数を書く読み方ができた（line-reply-prompts を修正）
//   ②AI が書いてスタッフが送らなかった文（「複数のお部屋をまとめてご案内できるよう準備いたします」）が
//     ai_reply_knowledge に学習として入り、次の生成で再生産されていた
//   ③出口に落とす層が無かった（← このファイル）

/** 数のまとめ語（名前を並べた後には要らない）。実送信0件の形だけを対象にする */
const VAGUE_QUANTIFIER_RE = /(?:これら|それら)?複数(?:の|件の)?\s*(?:物件|お?部屋)(?:について|につきまして|に(?:つき)?)?|(?:これら|それら)の(?:物件|お?部屋)(?:について|につきまして)?/;
/** 物件名の列挙（「A・B・C、」の形）。この直後の数のまとめ語だけを落とす */
const NAME_LIST_RE = /[^\n、。！!？?]{2,40}・[^\n、。！!？?]{2,40}(?:・[^\n、。！!？?]{2,40})*/;

export type VagueQuantifierResult = { text: string; removed: string[] };

/**
 * 物件名を並べた直後の数のまとめ語（「複数の物件について」）を落とす。
 * ・名前の列挙が同じ文に無ければ触らない（「複数のお部屋をまとめてご案内」のような別の文脈は別の層の担当）
 * ・落とした後に助詞が壊れないよう「、の物件について」（実送信の形）に揃える
 */
export function stripVagueQuantifier(text: string): VagueQuantifierResult {
  const src = text ?? "";
  if (!src.trim()) return { text: src, removed: [] };
  const removed: string[] = [];
  const lines = src.split("\n").map((line) => {
    // 文ごとに見る（1行に複数の文がある通もある）
    return line.split(/(?<=[。！!？?])/).map((s) => {
      const m = VAGUE_QUANTIFIER_RE.exec(s);
      if (!m) return s;
      const before = s.slice(0, m.index);
      // 直前に物件名の列挙があるか（「A・B・C、」）。無ければ触らない
      if (!NAME_LIST_RE.test(before)) return s;
      const after = s.slice(m.index + m[0].length);
      removed.push(m[0]);
      // 「〜、」で終わっていれば「の物件について」に揃える（実送信の形）。それ以外はそのまま繋ぐ
      const obj = /お?部屋/.test(m[0]) ? "お部屋" : "物件";
      const joiner = /[、,]\s*$/.test(before) ? `の${obj}について` : "";
      return `${before}${joiner}${after}`;
    }).join("");
  });
  if (removed.length === 0) return { text: src, removed: [] };
  return { text: lines.join("\n"), removed };
}

