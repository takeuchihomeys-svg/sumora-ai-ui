// ── Extract a top-level JS object literal by brace-counting ─────────────────
function extractJsObject(src, varName) {
  const re = new RegExp(`(?:const|var|let)\\s+${varName}\\s*=\\s*\\{`);
  const m  = re.exec(src);
  if (!m) throw new Error(`${varName} not found in source`);

  const start = m.index + m[0].length - 1; // index of opening '{'
  let depth = 0, i = start, inStr = false, strChar = '';

  while (i < src.length) {
    const ch = src[i];
    if (inStr) {
      if (ch === '\\') { i += 2; continue; }
      if (ch === strChar) inStr = false;
    } else {
      if (ch === '"' || ch === "'" || ch === '`') { inStr = true; strChar = ch; }
      else if (ch === '{') depth++;
      else if (ch === '}') { depth--; if (depth === 0) break; }
    }
    i++;
  }

  const block = src.slice(start, i + 1);
  // eslint-disable-next-line no-new-func
  return new Function(`return (${block})`)();
}

// ── Main ─────────────────────────────────────────────────────────────────────
function build() {
  const src = fs.readFileSync(INPUT, 'utf8');

  const lineStationOrder = extractJsObject(src, 'LINE_STATION_ORDER');
  console.log(`Lines loaded: ${Object.keys(lineStationOrder).length}`);

  // graph: Map<stationName, { lines: Set, adjSet: Map<key,entry>, transfers: Set }>
  const graph = new Map();

  function node(name) {
    if (!graph.has(name)) graph.set(name, { lines: new Set(), adjSet: new Map(), transfers: new Set() });
    return graph.get(name);
  }

  // Build line adjacency edges
  for (const [lineName, stations] of Object.entries(lineStationOrder)) {
    for (let i = 0; i < stations.length; i++) {
      const s = stations[i];
      node(s).lines.add(lineName);

      if (i > 0) {
        const p = stations[i - 1];
        // Keys must encode direction to avoid collision when a station has both
        // a predecessor AND a successor on the same line with an identical name pattern.
        node(s).adjSet.set(`<${p}|${lineName}`, [p, lineName]);  // s←p
        node(p).adjSet.set(`>${s}|${lineName}`, [s, lineName]);  // p→s
      }
    }
  }

  // Apply named transfers (bidirectional, skip missing stations with a warning)
  for (const [a, b] of NAMED_TRANSFERS) {
    const missing = [a, b].filter(n => !graph.has(n));
    if (missing.length) { console.warn(`  WARN: unknown station(s): ${missing.join(', ')}`); continue; }
    graph.get(a).transfers.add(b);
    graph.get(b).transfers.add(a);
  }

  console.log(`Stations: ${graph.size}`);

  // Serialize
  const lines = [];
  for (const [name, nd] of graph) {
    const linesArr     = JSON.stringify([...nd.lines]);
    const adjArr       = JSON.stringify([...nd.adjSet.values()]);
    const transfersArr = JSON.stringify([...nd.transfers]);
    lines.push(`  ${JSON.stringify(name)}: { lines: ${linesArr}, adj: ${adjArr}, transfers: ${transfersArr} }`);
  }

  const out =
    `// Auto-generated by build-transit-graph.js — DO NOT EDIT MANUALLY\n` +
    `// Source: chrome-extension/popup-maps.js (LINE_STATION_ORDER)\n` +
    `// Run:    node build-transit-graph.js\n` +
    `// Stations: ${graph.size}  Lines: ${Object.keys(lineStationOrder).length}\n` +
    `const TRANSIT_GRAPH = {\n` +
    lines.join(',\n') +
    `\n};\n`;

  fs.writeFileSync(OUTPUT, out, 'utf8');
  console.log(`Output: ${OUTPUT}`);
}

build();
