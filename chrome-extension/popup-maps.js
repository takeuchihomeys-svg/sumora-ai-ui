// 指定駅からN分以内に到達できる全駅を返す（Dijkstra）
function getReachableStations(startStation, maxMinutes) {
  if (!METRO_GRAPH[startStation]) return [];
  const dist = { [startStation]: 0 };
  const queue = [[0, startStation]];
  while (queue.length) {
    queue.sort((a, b) => a[0] - b[0]);
    const [d, u] = queue.shift();
    if (d > (dist[u] ?? Infinity)) continue;
    for (const [v, w] of (METRO_GRAPH[u] || [])) {
      const nd = d + w;
      if (nd <= maxMinutes && (dist[v] === undefined || nd < dist[v])) {
        dist[v] = nd;
        queue.push([nd, v]);
      }
    }
  }
  return Object.keys(dist).filter(s => s !== startStation);
}

