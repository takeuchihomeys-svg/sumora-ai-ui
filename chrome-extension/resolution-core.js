// 地名トークン → { city_code, ward_name } or null
function resolveWardLocal(token) {
  const ward = resolveWardLoose(String(token || "").trim());
  if (!ward || !WARD_CODE_MAP[ward]) return null;
  return { city_code: WARD_CODE_MAP[ward], ward_name: ward };
}

// 駅トークン → { station_name, route_id, itandi_line, reins_line }（+全路線の配列） or null
function resolveStationLocal(token) {
  const st = resolveStation(String(token || ""));
  if (!st) return null;
  const lines = _stationLines(st);
  const route_ids = [], itandi_lines = [], reins_lines = [];
  for (const l of lines) {
    const id = lineNameToRouteId(l);
    if (id && !route_ids.includes(id)) route_ids.push(id);
    const canon = lineNameToCanonical(l) || l;
    const iv = ITANDI_LINE_MAP_FILL[canon];
    if (iv) (Array.isArray(iv) ? iv : [iv]).forEach(v => { if (!itandi_lines.includes(v)) itandi_lines.push(v); });
    const rv = REINS_LINE_MAP[canon];
    if (rv && !reins_lines.includes(rv)) reins_lines.push(rv);
  }
  return {
    station_name: st,
    route_id: route_ids[0] || null,
    itandi_line: itandi_lines[0] || null,
    reins_line: reins_lines[0] || null,
    route_ids, itandi_lines, reins_lines,
  };
}

