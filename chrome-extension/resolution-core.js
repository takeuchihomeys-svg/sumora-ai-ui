// baseConditions: { desired_area, areas[], lines[], stations[], area_mode, rent_max, building_age }
// opts: { isWide = false, learned = { wards:{}, stations:{}, lineOrder:{} } }
// 戻り値は resolve-search-conditions API のレスポンス形状と1:1（マージコード変更不要）
function resolveConditionsLocal(baseConditions, opts) {
  opts = opts || {};
  const isWide = opts.isWide === true;
  _setLearned(opts.learned);

  const c = baseConditions || {};
  const desired_area = String(
    c.desired_area || (Array.isArray(c.areas) ? c.areas.join("・") : "") || ""
  ).trim();
  const areaMode = c.area_mode || "auto";

  // ① エリア文字列の解決（popup.js buildAreaRouteCodes と同一ロジック + 付帯情報収集）
  const col = { ward_names: [], station_names: [], realpro_lines: [], detail_area: null };
  const { city_codes, route_ids } = buildAreaRouteCodes({ desired_area }, areaMode, col);

  const unknown_extra = [];
  // 範囲展開・前後駅展開の対象（エリア由来 + 明示駅、解決順）
  const resolvedStations = [...col.station_names];

  // ② 明示 stations[] の解決
  for (const tok of (Array.isArray(c.stations) ? c.stations : [])) {
    const raw = String(tok || "").trim();
    if (!raw) continue;
    const st = resolveStation(raw);
    if (!st) { unknown_extra.push(raw); continue; }
    if (!col.station_names.includes(st)) col.station_names.push(st);
    if (!resolvedStations.includes(st)) resolvedStations.push(st);
    const lines = _stationLines(st);
    lines.forEach(l => {
      const id = lineNameToRouteId(l);
      if (id && !route_ids.includes(id)) route_ids.push(id);
      if (id) {
        const canon = lineNameToCanonical(l) || l;
        if (!col.realpro_lines.includes(canon)) col.realpro_lines.push(canon);
      }
    });
  }

  // ③ 明示 lines[] の解決
  for (const ln of (Array.isArray(c.lines) ? c.lines : [])) {
    const raw = String(ln || "").trim();
    if (!raw) continue;
    const canon = lineNameToCanonical(raw);
    if (!canon) { unknown_extra.push(raw); continue; }
    const id = LINE_ROUTE_MAP[canon];
    if (id && !route_ids.includes(id)) route_ids.push(id);
    if (!col.realpro_lines.includes(canon)) col.realpro_lines.push(canon);
  }

  // ④ 広げて検索: 各解決済み駅の路線上前後1駅を追加（popup 駅モード呼び出し箇所と同一）
  if (isWide) {
    for (const st of [...resolvedStations]) {
      getAdjacentStations(st, _stationLines(st)).forEach(adj => {
        if (!col.station_names.includes(adj)) col.station_names.push(adj);
      });
    }
  }

  // ⑤ 「AからBまで」: 連続する解決済み駅ペア間の中間駅を展開
  for (let i = 0; i + 1 < resolvedStations.length; i++) {
    expandStationRange(resolvedStations[i], resolvedStations[i + 1]).forEach(mid => {
      if (!col.station_names.includes(mid)) col.station_names.push(mid);
    });
  }

  // ⑥ itandi / REINS 路線名（収集済みリアプロ正規路線名から変換）
  const itandi_line_names = [];
  const reins_line_names = [];
  for (const line of col.realpro_lines) {
    const iv = ITANDI_LINE_MAP_FILL[line];  // 値は string または string[]
    if (iv) (Array.isArray(iv) ? iv : [iv]).forEach(v => {
      if (!itandi_line_names.includes(v)) itandi_line_names.push(v);
    });
    const rv = REINS_LINE_MAP[line];
    if (rv && !reins_line_names.includes(rv)) reins_line_names.push(rv);
  }

  // ⑦ 未解決トークン = computeUnknownTokens(エリア文字列) ∪ 未解決の明示駅・明示路線
  const unknown_tokens = computeUnknownTokens(desired_area);
  unknown_extra.forEach(t => { if (!unknown_tokens.includes(t)) unknown_tokens.push(t); });

  // ⑧ 家賃・築年数（広げて検索時の緩和ルール）
  const rentNum = (c.rent_max === null || c.rent_max === undefined || c.rent_max === "")
    ? NaN : Number(c.rent_max);
  const ageNum = (c.building_age === null || c.building_age === undefined || c.building_age === "")
    ? NaN : Number(c.building_age);
  const rent_max_resolved = isFinite(rentNum)
    ? (isWide ? rentNum + (rentNum <= 100000 ? 5000 : 10000) : rentNum)
    : null;
  const building_age_resolved = isFinite(ageNum)
    ? (isWide ? ageNum + 5 : ageNum)
    : null;

  return {
    city_codes,
    route_ids,
    station_names: col.station_names,
    ward_names: col.ward_names,           // city_codes に対応する市区フル名（itandi 用）
    itandi_line_names,
    reins_line_names,
    // 既存 background ルール準拠: 市区が1つに確定した場合のみセット（2区以上は null）
    detail_ward: (city_codes.length === 1 && col.ward_names.length >= 1) ? col.ward_names[0] : null,
    detail_area: col.detail_area,         // 区名そのものではない地名トークン（例: "喜連西"）
    unknown_tokens,
    rent_max_resolved,
    building_age_resolved,
  };
}

